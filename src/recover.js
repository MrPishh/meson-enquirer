import { config } from './config.js'
import { getSwaps, SWAP_BATCH_SIZE } from './meson.js'
import { readSwapEmbed, readWalletEmbed, followUpKind } from './render.js'
import { getTicket, rememberSwap } from './ticket-state.js'
import { watchSwap, syncFollowUps } from './watch.js'
import { admitMessage, retryDelay, worthRetrying } from './tickets.js'
import { canReply } from './discord-util.js'

// =============================================================================
//   Startup
// =============================================================================

/** How much of a ticket's history is read, in pages of 100 messages — far more than a ticket holds. */
const HISTORY_PAGES = 10

/** Tickets recover one after another (each first attempt), so a restart does not fire every Meson and Discord request at once. */
let chain = Promise.resolve()

/**
 * ClientReady entry point: claim every ticket channel's queue, then recover them one by one.
 * Channels are claimed synchronously, before any message can arrive; active threads are fetched first, so a message in a ticket thread during that moment is handled unrecovered.
 */
export async function recoverTickets (client) {
  for (const guild of client.guilds.cache.values()) {
    for (const channel of guild.channels.cache.values()) {
      if (channel.isTextBased() && !channel.isVoiceBased() && canReply(channel)) claim(channel)
    }
  }
  for (const guild of client.guilds.cache.values()) {
    const { threads } = await guild.channels.fetchActiveThreads().catch(() => ({ threads: new Map() }))
    for (const thread of threads.values()) if (canReply(thread)) claim(thread)
  }
  await chain
}

/**
 * Put a channel's recovery at the front of its ticket queue.
 * If Meson is down, the ticket is retried until it works, backing off like a ticket message (retryDelay) — with its live messages still waiting behind; it stops only when the ticket is gone or Discord refused (worthRetrying).
 */
function claim (channel) {
  const t = getTicket(channel.id)
  const first = chain.then(() => tryRecover(t, channel))
  chain = first
  t.queue = t.queue.then(() => first).then(async (ok) => {
    for (let attempt = 1; ok === false; attempt++) {
      const wait = retryDelay(attempt)
      console.error(`#${channel.name}: retrying recovery in ${wait / 1000}s`)
      await new Promise((resolve) => setTimeout(resolve, wait))
      ok = await tryRecover(t, channel)
    }
  })
}

/** One recovery attempt: true if done, false (logged) if it failed and is worth retrying, null if it is not worth retrying (ticket gone, Discord refused). */
async function tryRecover (t, channel) {
  try {
    await recoverTicket(t, channel)
    return true
  } catch (err) {
    if (!worthRetrying(channel, err)) {
      console.error(`#${channel.name}: recovery failed, not retried — ticket gone or Discord refused —`, err.message)
      return null
    }
    console.error(`#${channel.name}: recovery failed —`, err.message)
    return false
  }
}

// =============================================================================
//   Rebuilding one ticket
// =============================================================================

/** The channel's messages, oldest first (up to HISTORY_PAGES × 100). */
async function readHistory (channel) {
  const all = []
  let before
  for (let page = 0; page < HISTORY_PAGES; page++) {
    const batch = await channel.messages.fetch({ limit: 100, before })
    all.push(...batch.values())
    if (batch.size < 100) break
    before = batch.last().id
  }
  return all.sort((a, b) => (BigInt(a.id) < BigInt(b.id) ? -1 : 1))
}

/**
 * Rebuild a ticket from its history and resume it.
 * Everything is looked up before the ticket is touched, so an attempt that fails half-way (Meson down) leaves nothing half-made for the retry.
 */
async function recoverTicket (t, channel) {
  const me = channel.client.user.id
  const history = await readHistory(channel)

  // The bot's own messages: details embeds (in posting order), wallet embeds, and follow-ups by the embed they reply to.
  const found = []
  const addresses = new Set()
  const followUps = new Map() // details message ID → { processing, outcome }
  let lastOwn = -1
  history.forEach((m, i) => {
    // /meson-query answers are not part of the ticket's own flow.
    if (m.author.id !== me || m.interactionMetadata) return
    lastOwn = i
    const swap = readSwapEmbed(m.embeds[0])
    if (swap && !found.some((f) => f.swapId === swap.swapId)) found.push({ ...swap, message: m })
    const wallet = readWalletEmbed(m.embeds[0])
    if (wallet) addresses.add(wallet.toLowerCase())
    const kind = followUpKind(m.content)
    const to = m.reference?.messageId
    if (to && kind) followUps.set(to, { ...followUps.get(to), [kind]: m })
  })
  const handled = history.slice(0, lastOwn + 1)
  const missed = history.slice(lastOwn + 1).filter((m) => m.author.id !== me)
  if (!found.length && !missed.length) return

  // Re-check every swap, together (one request per SWAP_BATCH_SIZE); one Meson no longer knows is dropped (logged).
  const latestById = new Map()
  for (let i = 0; i < found.length; i += SWAP_BATCH_SIZE) {
    for (const [id, view] of await getSwaps(found.slice(i, i + SWAP_BATCH_SIZE).map((f) => f.swapId))) latestById.set(id, view)
  }
  const swaps = []
  for (const f of found) {
    const latest = latestById.get(f.swapId.toLowerCase())
    if (latest) swaps.push({ f, latest })
    else console.error(`#${channel.name}: ${f.swapId} no longer found on Meson — not recovered`)
  }

  // Commit: the ticket as it was before the restart.
  t.swaps = swaps.map(({ f, latest }, i) => ({
    n: i + 1,
    swapId: latest.swapId,
    message: f.message,
    latest,
    processing: followUps.get(f.message.id)?.processing ?? null,
    outcome: followUps.get(f.message.id)?.outcome,
  }))
  for (const e of t.swaps) rememberSwap(t, e.latest)
  for (const a of addresses) t.addresses.add(a)
  // Other bots' messages already behind the bot's last reply count as read (Ticket Tool's form).
  t.botMessagesSeen = Math.min(config.scanLimit, handled.filter((m) => m.author.bot && m.author.id !== me).length)

  // Labels and "closed soon" as they should be now, then follow every swap again.
  for (const e of t.swaps) await syncFollowUps(t, e)
  for (const e of t.swaps) {
    await watchSwap(t, e, { resumed: true }).catch((err) => console.error(`#${channel.name}: resuming ${e.swapId} failed —`, err.message))
  }

  // Messages missed while down. Fetched messages carry no member, so load it for the staff check.
  for (const m of missed) {
    if (!m.author.bot && !m.member) await channel.guild.members.fetch(m.author.id).catch(() => {})
    admitMessage(t, m)
  }

  const open = t.swaps.filter((e) => !e.outcome).length
  console.log(`#${channel.name}: recovered ${t.swaps.length} swap(s) after restart, ${open} still followed, ${missed.length} missed message(s) queued`)
}
