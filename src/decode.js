/**
 * Decoder for Meson's 32-byte "encoded swap".
 *
 * Meson packs the whole swap into one 32-byte word.
 * The explorer API returns it as `encoded` and decodes it in the browser, so there is no endpoint that hands back the chains or the amount directly — we have to unpack it here.
 *
 * Byte layout (big-endian, offsets are inclusive-exclusive):
 *
 *   [0,1)   version
 *   [1,6)   amount     (always 6 decimals, regardless of the token)
 *   [6,16)  salt
 *   [16,21) fee        (the LP fee, in the same 6-decimal units)
 *   [21,26) expireTs   (unix seconds)
 *   [26,28) outChain   (SLIP-44 coin type, e.g. 0x02ca = 714 = BNB)
 *   [28,29) outToken   (Meson token index, scoped to outChain)
 *   [29,31) inChain
 *   [31,32) inToken
 *
 * Verified byte-for-byte against the rendered explorer page for swaps across Solana, Tron, Bitcoin, Ethereum, Base, Arbitrum, BNB and Conflux.
 * Only the fields the bot shows are returned; version, salt and the encoded fee are skipped (the fee comes from the swap record's srFee + lpFee instead).
 */
