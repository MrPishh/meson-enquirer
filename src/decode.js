/** Unpack a 32-byte encoded swap (layout above) into amount, chains, tokens, expiry. */
export function decodeEncodedSwap (encoded) {
  if (typeof encoded !== 'string') throw new TypeError('encoded swap must be a string')
  const hex = encoded.startsWith('0x') || encoded.startsWith('0X') ? encoded.slice(2) : encoded
  if (!/^[0-9a-fA-F]{64}$/.test(hex)) {
    throw new Error(`encoded swap must be 32 bytes of hex, got ${encoded.length} chars`)
  }
  const b = Buffer.from(hex, 'hex')
  const int = (start, end) => Number(BigInt('0x' + b.subarray(start, end).toString('hex')))

  return {
    amount: BigInt('0x' + b.subarray(1, 6).toString('hex')),
    expireTs: int(21, 26),
    outChain: '0x' + b.subarray(26, 28).toString('hex'),
    outToken: b[28],
    inChain: '0x' + b.subarray(29, 31).toString('hex'),
    inToken: b[31],
  }
}

// =============================================================================
//   Formatting
// =============================================================================

/** Meson encodes every amount with 6 decimals, whatever the token's own are. */
const AMOUNT_DECIMALS = 6

/** One whole token in the 6-decimal amount units (1_000_000n). */
const UNITS = 10n ** BigInt(AMOUNT_DECIMALS)

/**
 * Format a 6-decimal amount for display, trimming trailing zeros the way the explorer does (358868497 -> "358.868497", 520 -> "0.00052").
 */
export function formatAmount (units) {
  const v = BigInt(units)
  const neg = v < 0n
  const abs = neg ? -v : v
  const whole = abs / UNITS
  const frac = (abs % UNITS).toString().padStart(AMOUNT_DECIMALS, '0').replace(/0+$/, '')
  return `${neg ? '-' : ''}${whole}${frac ? '.' + frac : ''}`
}
