/** When presets.json was generated — logged at startup. */
export const generatedAt = presets.generatedAt

/** Number of known chains — logged at startup. */
export const chainCount = Object.keys(presets.chains).length

/**
 * The presets.json entry for a chain, or null if unknown.
 * @param {string} shortSlip44 e.g. "0x02ca"
 * @returns {{id:string,name:string,alias:string|null,explorer:string|null,addressFormat:string|null,tokens:Record<string,string>}|null}
 */
function getChain (shortSlip44) {
  if (!shortSlip44) return null
  return presets.chains[String(shortSlip44).toLowerCase()] ?? null
}

/** Human chain name, falling back to the raw id so output is never blank. */
export function chainName (shortSlip44) {
  return getChain(shortSlip44)?.name ?? `Unknown chain (${shortSlip44})`
}

/** Meson's network ID for a chain (e.g. "arb") — the key rpcs.meson.fi uses — or null if unknown. */
export function chainId (shortSlip44) {
  return getChain(shortSlip44)?.id ?? null
}

/** Token symbol for a chain-scoped Meson token index. */
export function tokenSymbol (shortSlip44, tokenIndex) {
  return getChain(shortSlip44)?.tokens?.[String(tokenIndex)] ?? `token#${tokenIndex}`
}

/** Whether the table knows this chain and this token on it — false means the swap would show "Unknown chain" or "token#NN". */
export const isKnownPair = (shortSlip44, tokenIndex) => getChain(shortSlip44)?.tokens?.[String(tokenIndex)] !== undefined

