/**
 * Chain and token lookups for decoded swaps.
 *
 * The numbers inside an encoded swap are a SLIP-44 coin type (`0x02ca` = BNB) and a Meson token index scoped to that chain (`34` on BNB = BSC-USD).
 * The documented relayer endpoint `/api/v1/list` publishes symbols and decimals but *not* those two numbers, so it cannot be used to decode a swap.
 * The only published source that carries both is the explorer's own preset table, embedded in its JavaScript bundle.
 *
 * src/presets.json is the starting table (written by `npm run refresh-presets`). While running, the bot also reads the live table and merges it in, in memory only (fetchLiveChains, mergeChains; when it does so: refreshPresets in meson.js), so a chain or token Meson adds is known without a code change or restart.
 * This file loads no settings, so `npm run refresh-presets` needs no `.env`.
 */
