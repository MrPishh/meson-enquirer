/** Where the bundle holding the preset table is served from. */
const ORIGIN = 'https://explorer.meson.fi'

/** The bundle's preset table also lists test networks; those share a chain number with their mainnet, so they must be left out. */
const TESTNET = /testnet|devnet|ropsten|goerli|sepolia|holesky|fuji|mumbai|amoy/i

/** Fewer chains than this means the bundle was misread — such a table is refused rather than used. */
const MIN_CHAINS = 40

/** A single backslash, for the two scanners below. */
const BACKSLASH = String.fromCharCode(92)

/** GET a URL as text, failing on any non-2xx status or after `timeoutMs`. */
async function fetchText (url, timeoutMs) {
  const res = await fetch(url, { signal: AbortSignal.timeout(timeoutMs), headers: { 'user-agent': 'meson-ticket-bot/presets' } })
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`)
  return res.text()
}

/** Find the end index of the JSON value starting at `start` (must be '{'). */
function endOfObject (s, start) {
  let depth = 0
  let inStr = false
  let esc = false
  for (let i = start; i < s.length; i++) {
    const c = s[i]
    if (inStr) {
      if (esc) esc = false
      else if (c === BACKSLASH) esc = true
      else if (c === '"') inStr = false
      continue
    }
    if (c === '"') inStr = true
    else if (c === '{') depth++
    else if (c === '}' && --depth === 0) return i + 1
  }
  return -1
}

/**
 * The bundle's object literals are minified JavaScript, not JSON, and use two string escapes JSON.parse rejects: `\xNN` for non-ASCII characters (B² Network is `"B\xb2 Network"`) and `\'` (`"Merlin\'s Seal USDC"`).
 * Rewrite them to `\u00NN` and a plain `'` — only when the backslash is not itself escaped (an odd run of backslashes).
 */
const jsToJson = (s) => s.replace(new RegExp(`(${BACKSLASH}${BACKSLASH}+)(x([0-9a-fA-F]{2})|')`, 'g'), (m, slashes, esc, hex) => {
  if (slashes.length % 2 === 0) return m
  const kept = slashes.slice(0, -1)
  return hex ? `${kept}${BACKSLASH}u00${hex}` : `${kept}'`
})

/** Every chain object (one with a `shortSlip44`) in a bundle chunk, in bundle order. */
function extractChains (js) {
  const found = []
  let i = 0
  while ((i = js.indexOf('{"id":"', i)) !== -1) {
    const end = endOfObject(js, i)
    if (end === -1) break
    const literal = js.slice(i, end)
    let obj
    try {
      obj = JSON.parse(jsToJson(literal))
    } catch {
      // A chain that cannot be parsed would silently vanish from the table (its swaps then show "Unknown chain") — say so.
      if (literal.includes('"shortSlip44"')) console.error(`skipped an unparseable chain: ${literal.slice(0, 80)}…`)
      i++
      continue
    }
    if (obj && typeof obj === 'object' && obj.shortSlip44) found.push(obj)
    i = end
  }
  return found
}

/**
 * Read the current chain and token table from the live explorer bundle, keyed by lower-case `shortSlip44`.
 * Later definitions win: the bundle carries an older preset generation first, then the current one (which uses the live token indexes).
 * All or nothing — any chunk that cannot be read fails the whole read, because the one missed could hold the current generation, and the older one would mislabel tokens.
 * @param {{timeoutMs?: number}} [opts] timeout of each request
 * @throws if the explorer cannot be read or the table looks wrong
 */
export async function fetchLiveChains ({ timeoutMs = 30000 } = {}) {
  const html = await fetchText(`${ORIGIN}/`, timeoutMs)
  const chunks = [...new Set([...html.matchAll(/\/_next\/static\/chunks\/[\w/.-]+\.js/g)].map((m) => m[0]))]
  if (!chunks.length) throw new Error('no webpack chunks found on the explorer homepage')

  const chains = {}
  let hits = 0
  for (const path of chunks) {
    const js = await fetchText(ORIGIN + path, timeoutMs)
    if (!js.includes('"shortSlip44"')) continue
    hits++
    for (const c of extractChains(js)) {
      if (TESTNET.test(c.id) || TESTNET.test(c.name ?? '')) continue
      chains[c.shortSlip44.toLowerCase()] = {
        id: c.id,
        name: c.name,
        alias: c.alias ?? null,
        explorer: c.explorer ?? null,
        addressFormat: c.addressFormat ?? null,
        tokens: Object.fromEntries((c.tokens ?? []).map((t) => [String(t.tokenIndex), t.symbol])),
      }
    }
  }
  if (!hits) throw new Error('no chunk contained the preset table — the explorer bundle layout changed')
  const count = Object.keys(chains).length
  if (count < MIN_CHAINS) throw new Error(`only ${count} chains extracted, refusing a truncated table`)
  return chains
}

/**
 * Merge a live table into the one in use, in memory only.
 * The live values win, but nothing is removed: a chain or token Meson drops can still appear on older swaps, and its name is still right for those.
 * @param {Record<string, object>} live from fetchLiveChains
 * @returns {{added: string[], relabelled: string[]}} what changed, in words for the log
 */
export function mergeChains (live) {
  const added = []
  const relabelled = []
  for (const [key, chain] of Object.entries(live)) {
    const old = presets.chains[key]
    if (!old) added.push(`chain ${chain.name} (${key})`)
    for (const [index, symbol] of Object.entries(chain.tokens)) {
      if (old && old.tokens[index] === undefined) added.push(`token ${symbol} on ${chain.name}`)
      else if (old && old.tokens[index] !== symbol) relabelled.push(`${chain.name} token #${index}: ${old.tokens[index]} is now ${symbol}`)
    }
    presets.chains[key] = { ...chain, tokens: { ...old?.tokens, ...chain.tokens } }
  }
  return { added, relabelled }
}

