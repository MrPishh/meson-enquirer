/** Path segment each explorer uses for a transaction. Default is `/tx/`. */
const TX_PATH = {
  tron: '/transaction/',
  ckb: '/transaction/',
  ton: '/transaction/',
  aptos: '/txn/',
  sui: '/txblock/',
}

/** Explorers that need a query string to pin the network. */
const TX_SUFFIX = {
  aptos: '?network=mainnet',
}

/** A block-explorer URL for a transaction on the given chain, or null. */
export function txUrl (shortSlip44, hash) {
  const chain = getChain(shortSlip44)
  if (!chain?.explorer || !hash) return null
  const fmt = chain.addressFormat ?? 'ethers'
  const path = TX_PATH[fmt] ?? '/tx/'
  return `${chain.explorer}${path}${hash}${TX_SUFFIX[fmt] ?? ''}`
}

/** A block-explorer URL for an address on the given chain, or null. */
export function addressUrl (shortSlip44, address) {
  const chain = getChain(shortSlip44)
  if (!chain?.explorer || !address) return null
  const fmt = chain.addressFormat ?? 'ethers'
  const path = fmt === 'aptos' ? '/account/' : '/address/'
  return `${chain.explorer}${path}${address}${TX_SUFFIX[fmt] ?? ''}`
}
