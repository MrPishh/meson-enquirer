/** Meson's own status of every chain's RPC nodes (public, no key): `{data: {<chainId>: [{healthy, latency, …}]}}`. */
const RPCS = 'https://rpcs.meson.fi/'

/** Last chain health check: when, and which chain IDs had no healthy node. */
let health = { at: 0, troubled: new Set(), pending: null }

/**
 * Chain IDs (e.g. "arb") where none of Meson's RPC nodes is healthy right now, cached for CHAIN_HEALTH_CACHE_SECONDS — one request covers every chain, however many swaps ask.
 * Only a hint: turned off (0), or the check failing, gives an empty set and never an error.
 */
async function troubledChainIds () {
  if (config.chainHealthMs <= 0) return new Set()
  if (Date.now() - health.at < config.chainHealthMs) return health.troubled
  health.pending ??= fetchChainHealth().finally(() => { health.pending = null })
  return health.pending
}

/** One chain health request; a failure is logged and counts as "no known problems" until the next check is due. */
async function fetchChainHealth () {
  let troubled = new Set()
  const ac = new AbortController()
  const timer = setTimeout(() => ac.abort(), config.mesonTimeoutMs)
  try {
    const res = await fetch(RPCS, { signal: ac.signal, headers: { accept: 'application/json', 'user-agent': UA } })
    const body = await res.json()
    // A chain counts as troubled only when *every* node is down — one bad node out of many is Meson's problem, not the swap's.
    for (const [id, nodes] of Object.entries(body?.data ?? {})) {
      if (Array.isArray(nodes) && nodes.length && !nodes.some((n) => n.healthy)) troubled.add(id)
    }
    if (troubled.size) console.log(`chain health: no healthy node on ${[...troubled].join(', ')}`)
  } catch (err) {
    console.error('chain health check failed (no network notes until the next one) —', err.message)
    troubled = new Set()
  } finally {
    clearTimeout(timer)
  }
  health = { ...health, at: Date.now(), troubled }
  return troubled
}

/** Fill in `troubledChains` (display names) on every unfinished swap view whose source or destination chain is troubled. */
async function addChainHealth (views) {
  const open = views.filter((v) => !isFinished(v.status))
  if (!open.length) return
  const troubled = await troubledChainIds()
  for (const v of open) {
    v.troubledChains = [...new Set([v.from, v.to].filter((side) => troubled.has(side.chainId)).map((side) => side.chain))]
  }
}

