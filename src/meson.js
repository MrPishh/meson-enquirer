/**
 * List the swaps an address took part in (as either sender or recipient), newest first, as the explorer's "Swaps for Address" page shows them.
 *
 * @param {string} address
 * @param {{page?: number, size?: number}} [opts] page is 0-based, matching the API
 * @returns {Promise<{swaps: ReturnType<typeof toSwapView>[], page: number, size: number, hasMore: boolean}>}
 */
export async function listSwapsForAddress (address, { page = 0, size = 10 } = {}) {
  const addr = String(address).trim()
  const res = await getJson(`${EXPLORER}/api/v1/address/${encodeURIComponent(addr)}/swap?page=${page}&size=${size}`)
  if (!res.ok) {
    // Meson currently answers an unknown or malformed address with an empty list (HTTP 200, checked 2026-10-27), so this is a just-in-case: an `error` body is a rejection of the address, flagged `rejected` to tell it apart from Meson being down (which throws from getJson instead, and is worth retrying).
    throw Object.assign(new Error(res.error?.message ?? `could not list swaps for ${addr}`), { rejected: true })
  }
  const list = Array.isArray(res.result?.list) ? res.result.list : []
  return {
    swaps: list.map(toSwapView),
    page,
    size,
    // The API returns no total count; a short page is the only end-of-list signal it gives.
    hasMore: list.length === size,
  }
}

/** The address endpoint rejects anything larger ("Size cannot exceed 20"). */
const MAX_PAGE_SIZE = 20

/**
 * An address's swaps that are *not* Done or Cancelled within the last `maxAgeDays` (both are finished — a cancel already returned the funds) — what a ticket opened with only a wallet address actually needs to see.
 *
 * The API has no status or date filter (only `failed=true` and `rewardId`, neither of which helps) and no total count, so this pages newest-first at the API's maximum size and filters locally.
 * To keep a busy wallet from costing dozens of requests it stops at whichever comes first:
 *   - 'end'    the wallet has no older swaps
 *   - 'age'    reached a swap older than `maxAgeDays`
 *   - 'pages'  hit `maxPages` requests — older swaps were not checked
 * The result says which, so the embed can say how far back it looked.
 *
 * @returns {Promise<{swaps: object[], scanned: number, since: Date, stoppedBy: 'end'|'age'|'pages'}>}
 */
export async function listUnfinishedSwapsForAddress (address, { maxAgeDays = config.addressLookbackDays, maxPages = config.addressMaxPages } = {}) {
  const since = new Date(Date.now() - maxAgeDays * 24 * 60 * 60 * 1000)
  const swaps = []
  let scanned = 0
  const done = (stoppedBy) => ({ swaps, scanned, since, stoppedBy })

  for (let page = 0; page < maxPages; page++) {
    const { swaps: batch, hasMore } = await listSwapsForAddress(address, { page, size: MAX_PAGE_SIZE })
    for (const swap of batch) {
      if (swap.requestedAt && swap.requestedAt < since) return done('age')
      scanned++
      if (!isFinished(swap.status)) swaps.push(swap)
    }
    if (!hasMore) return done('end')
  }
  return done('pages')
}
