/**
 * Look up a swap from anything a user might paste — swap ID, encoded swap, source or destination tx hash, Solana signature — and return a flat, display-ready object.
 * The explorer's search resolves all of them the same way, so there is no need to tell them apart.
 * @param {string} query
 */
export async function lookupSwap (query) {
  return getSwap(await resolveSwapId(String(query).trim()))
}

/** A swap by its known swap ID (one request — for a single lookup; re-checks of several swaps use getSwaps). */
async function getSwap (swapId) {
  const view = toSwapView(await fetchSwap(swapId))
  await addChainHealth([view])
  return view
}

/** Most swap IDs sent in one getSwaps request (20 checked against the live API, 2026-10-28). */
export const SWAP_BATCH_SIZE = 20

/**
 * Several swaps by known swap ID in one request (what the background re-checks and restart recovery use), keyed by lower-case swap ID.
 * The explorer takes the IDs comma-separated (`/api/v1/swap/<id>,<id>`) and answers with an array of the same records as the single lookup — sorted, not in request order, duplicates merged, unknown IDs left out (so a missing key = not found).
 * Pass at most SWAP_BATCH_SIZE IDs.
 * @param {string[]} swapIds
 * @returns {Promise<Map<string, ReturnType<typeof toSwapView>>>}
 */
export async function getSwaps (swapIds) {
  if (!swapIds.length) return new Map()
  const res = await getJson(`${EXPLORER}/api/v1/swap/${swapIds.map(encodeURIComponent).join(',')}`)
  // One ID is answered with the swap itself (or a "not found" error), not an array.
  const list = !res.ok ? [] : Array.isArray(res.result) ? res.result : res.result ? [res.result] : []
  const views = list.map(toSwapView)
  await addChainHealth(views)
  return new Map(views.map((v) => [v.swapId.toLowerCase(), v]))
}

