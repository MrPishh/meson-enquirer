/** Step rank used by the explorer to find a swap's furthest step — copied from its bundle, order matters. */
const EXPLORER_STEP_RANK = ['FAILED', 'PENDING', 'REQUESTING', 'POSTED', 'BONDED', 'LOCKED', 'UNLOCKED', 'RELEASING', 'EXECUTED', 'CANCELLED', 'RELEASED', 'GASDROP']

/**
 * The status the Meson explorer shows for a swap — a line-for-line port of its own function (explorer bundle, called with the swap's events and `expireTs`), so the bot's heading always matches the explorer.
 * Returns the explorer's raw label, e.g. `DONE`, `RELEASING...`, `EXPIRED*`; a trailing `*` means an LP lock is still outstanding. See CONTEXT.md § Status derivation.
 */
function explorerStatus (events, expireTs) {
  const named = events.filter((e) => e.name)
  if (!named.length) return ''
  const fundsTaken = named.some((e) => ['POSTED', 'BONDED', 'LOCKED', 'EXECUTED'].includes(e.name) && e.hash)
  const locks = named.filter((e) => e.name === 'LOCKED').length
  const unlocks = named.filter((e) => ['RELEASED', 'UNLOCKED'].includes(e.name)).length
  const star = locks > unlocks ? '*' : ''
  // With nothing on-chain the explorer treats the swap as expired an hour early.
  const expired = (fundsTaken ? expireTs : expireTs - 3600) < Date.now() / 1000
  let step = named
    .filter((e) => (e.name.endsWith('ING') || e.hash) && e.name !== 'GASDROP')
    .map((e) => (e.pending ? 'PENDING' : e.name.endsWith(':FAILED') ? 'FAILED' : e.name))
    .sort((a, b) => EXPLORER_STEP_RANK.indexOf(b) - EXPLORER_STEP_RANK.indexOf(a))[0]

  if (step === 'RELEASED') return named.some((e) => e.name === 'EXECUTED') ? `DONE${star}` : `RELEASED${star}`
  if (step === 'CANCELLED') return `CANCELLED${star}`
  if (step === 'EXECUTED') return named.some((e) => e.name === 'UNLOCKED') ? 'UNLOCKED' : 'RELEASING...'
  if (step === 'RELEASING') {
    if (fundsTaken) return 'RELEASING'
    step = 'REQUESTING'
  }
  if (expired) return `EXPIRED${fundsTaken ? '*' : ''}`
  return star ? 'LOCKED' : step
}

/**
 * Derive the display status: the explorer's own label (explorerStatus), title-cased, plus what the bot does with it.
 * `label` is the bare word the code checks ("Expired"); `star` is the explorer's `*` (an LP lock still outstanding), shown after it wherever the status is displayed ("Expired*").
 * `done` + `ok`: Done / Released are finished (✅), Cancelled is finished (↩️); `ok` false means no ⏳ "completed shortly" promise.
 */
function deriveStatus (raw, decoded) {
  const events = Array.isArray(raw.events) ? raw.events : []
  const shown = explorerStatus(events, decoded.expireTs)
  const star = shown.includes('*') ? '*' : ''
  return { ...statusFor(shown.replace(/[*.]+$/, '')), star }
}

/** What the bot does with each explorer label (without its `*` / `...`). */
function statusFor (label) {
  switch (label) {
    case 'DONE': return { label: 'Done', detail: null, done: true, ok: true }
    // Released before the LP has executed — the recipient already has the funds.
    case 'RELEASED': return { label: 'Released', detail: null, done: true, ok: true }
    case 'CANCELLED': return { label: 'Cancelled', detail: null, done: true, ok: false }
    case 'RELEASING': return { label: 'Releasing', detail: null, done: false, ok: true }
    // UNLOCKED: the LP's lock on the target chain was undone — the swap will not go through, and the funds come back via a later CANCELLED.
    case 'UNLOCKED': return { label: 'Unlocked', detail: 'the swap did not go through — waiting for the funds to be returned', done: false, ok: false }
    case 'FAILED': return { label: 'Failed', detail: null, done: false, ok: false }
    case 'EXPIRED':
      // Deliberately say nothing about what happens next: support may cancel and refund it, or complete it from the contract — any promise here ("funds stay with the sender", "can no longer go through") can be wrong.
      return { label: 'Expired', detail: 'the swap was not completed in time', done: false, ok: false }
    case '':
    case 'PENDING': return { label: 'Pending', detail: null, done: false, ok: true }
    // REQUESTING / POSTED / BONDED / LOCKED (or a step the explorer adds later): its own word, still moving.
    default: return { label: label.charAt(0) + label.slice(1).toLowerCase(), detail: null, done: false, ok: true }
  }
}

/**
 * Done, Released or Cancelled: nothing left to chase (a cancel already returned the funds).
 * Left out of the wallet view, and what "ticket will close soon" waits for.
 * Expired / Failed / Unlocked are *not* finished — they are still watched until one of those.
 */
export const isFinished = (status) => ['Done', 'Released', 'Cancelled'].includes(status.label)

