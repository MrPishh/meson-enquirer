/**
 * Derive a single display status from the event list and expiry.
 *
 * Observed event names: POSTED, BONDED, LOCKED, UNLOCKED, EXECUTED, RELEASED, CANCELLED, and failure variants suffixed with ":FAILED".
 * An event may carry `pending: true` while its transaction is still confirming.
 */
function deriveStatus (raw, decoded) {
  const events = Array.isArray(raw.events) ? raw.events : []
  const byName = (n) => events.find((e) => String(e.name).toUpperCase().startsWith(n))

  const failed = events.find((e) => String(e.name).toUpperCase().includes('FAILED'))
  if (failed) {
    const step = String(failed.name).split(':')[0].toLowerCase()
    return { label: 'Failed', detail: `the ${step} transaction failed on-chain`, done: true, ok: false }
  }

  const cancelled = byName('CANCELLED')
  if (cancelled) return { label: 'Cancelled', detail: null, done: true, ok: false }

  const released = byName('RELEASED')
  if (released) {
    return released.pending
      ? { label: 'Releasing', detail: 'funds are being released to the recipient — destination transaction is confirming', done: false, ok: true }
      : { label: 'Done', detail: null, done: true, ok: true }
  }

  // UNLOCKED: the LP's lock on the target chain was undone — the swap will not go through, and the funds come back via a later CANCELLED.
  if (byName('UNLOCKED')) {
    return { label: 'Unlocked', detail: 'the swap did not go through — waiting for the funds to be returned', done: false, ok: false }
  }

  const expired = decoded.expireTs > 0 && Date.now() / 1000 > decoded.expireTs
  if (expired) {
    return {
      label: 'Expired',
      // Deliberately say nothing about what happens next: support may cancel and refund it, or complete it from the contract — any promise here ("funds stay with the sender", "can no longer go through") can be wrong.
      detail: 'the swap was not completed in time',
      done: true,
      ok: false,
    }
  }

  // Meanings per meson.dev's check-swap docs (see CONTEXT.md).
  if (byName('EXECUTED')) return { label: 'Executed', detail: 'the funds have been transferred to the liquidity provider on the source chain', done: false, ok: true }
  if (byName('LOCKED')) return { label: 'Locked', detail: 'the liquidity provider has locked funds on the destination chain', done: false, ok: true }
  if (byName('BONDED')) return { label: 'Bonded', detail: 'a liquidity provider has bonded the swap', done: false, ok: true }
  if (byName('POSTED')) return { label: 'Posted', detail: 'Meson has taken the funds on the source chain', done: false, ok: true }
  return { label: 'Pending', detail: 'no on-chain events yet', done: false, ok: true }
}

/**
 * Done or Cancelled: nothing left to chase (a cancel already returned the funds).
 * Left out of the wallet view, and what "ticket will close soon" waits for.
 * Expired / Failed / Unlocked are *not* finished — they need follow-up.
 */
export const isFinished = (status) => status.label === 'Done' || status.label === 'Cancelled'

// =============================================================================
//   Swap view
// =============================================================================

const toDate = (v) => (v ? new Date(v) : null)

/** Turn one raw swap record (from either endpoint — same shape) into the flat, display-ready view. */
function toSwapView (raw) {
  const decoded = decodeEncodedSwap(raw.encoded)
  const [fromAddress, toAddress] = Array.isArray(raw.fromTo) ? raw.fromTo : [null, null]

  const srFee = BigInt(raw.srFee ?? 0)
  const lpFee = BigInt(raw.lpFee ?? 0)
  const totalFee = srFee + lpFee
  const received = decoded.amount - totalFee

  const events = (raw.events ?? []).map((e) => ({
    name: e.name,
    hash: e.hash,
    pending: Boolean(e.pending),
    // The source-side events happen on the "in" chain, the release on the "out" chain.
    url: txUrl(String(e.name).toUpperCase().startsWith('RELEASED') ? decoded.outChain : decoded.inChain, e.hash),
  }))

  return {
    swapId: raw._id,
    encoded: raw.encoded,
    status: deriveStatus(raw, decoded),

    from: {
      chain: chainName(decoded.inChain),
      token: tokenSymbol(decoded.inChain, decoded.inToken),
      address: fromAddress,
      addressUrl: addressUrl(decoded.inChain, fromAddress),
      amount: formatAmount(decoded.amount),
    },
    to: {
      chain: chainName(decoded.outChain),
      token: tokenSymbol(decoded.outChain, decoded.outToken),
      address: toAddress,
      addressUrl: addressUrl(decoded.outChain, toAddress),
      amount: formatAmount(received < 0n ? 0n : received),
    },

    fee: {
      service: formatAmount(srFee),
      lp: formatAmount(lpFee),
      total: formatAmount(totalFee),
    },

    requestedAt: toDate(raw.created),
    releasedAt: toDate(raw.released),
    expiresAt: decoded.expireTs ? new Date(decoded.expireTs * 1000) : null,

    events,
    explorerUrl: `${EXPLORER}/swap/${raw._id}`,
  }
}

