/**
 * Meson swap lookup.
 *
 * Upstreams in play, none needing an API key:
 *
 *  - explorer.meson.fi/api/v1/search?q=...          resolves a swap ID, an encoded swap, an EVM tx hash or a Solana signature to a swap ID.
 *  - explorer.meson.fi/api/v1/swap/<swapId>         one swap's addresses, fees, timestamps and encoded swap.
 *  - explorer.meson.fi/api/v1/swap/<id>,<id>,…      the same for up to 20 swaps in one request (undocumented; getSwaps falls back to single lookups if it stops working).
 *  - explorer.meson.fi/api/v1/address/<addr>/swap   every swap an address took part in (either side), paginated with ?page=&size=, same record shape as the single-swap endpoint.
 *  - rpcs.meson.fi/                                 Meson's view of every chain's RPC nodes — only for the ⚠️ network notice (a hint; failures are ignored).
 *
 * The *documented* relayer endpoints (relayer.meson.fi/api/v1/swap?hash= and /api/v1/swap/<id>) give event hashes, chains, tokens and amounts but no wallet addresses, failed attempts or pending flags, and there is no address-history endpoint — not enough for the details embed or the explorer's status.
 * So swap data comes from the explorer API throughout.
 */
