/** Base URL of the Meson explorer — every API call and explorer link uses it. */
const EXPLORER = 'https://explorer.meson.fi'

/** User-Agent sent with every request. */
const UA = 'meson-ticket-bot'

/** A wait of about `ms`, randomly up to JITTER_PERCENT shorter or longer — every repeated request to Meson goes through it, so they never come at a fixed beat while averaging the same rate. */
export const jitter = (ms) => Math.round(ms * (1 + (Math.random() * 2 - 1) * config.jitterPercent / 100))

/** Thrown when the upstream clearly says "no such swap". */
export class SwapNotFound extends Error {
  constructor (query) {
    super(`No Meson swap found for \`${query}\``)
    this.name = 'SwapNotFound'
  }
}

/**
 * GET an explorer API URL.
 * Returns {ok:false, error} when the body carries an `error` (how upstream says "not found", with HTTP 400 *or* 404).
 * Retries network errors, 429, 5xx and non-JSON bodies with growing, jittered pauses (about 1s, 2s, 4s) — the host briefly serves an HTML error page during hiccups, and a 200 HTML page from a correct API path has been seen in production and cleared on retry.
 */
async function getJson (url, { timeoutMs = config.mesonTimeoutMs, retries = config.mesonRetries } = {}) {
  let lastErr
  for (let attempt = 0; attempt <= retries; attempt++) {
    const ac = new AbortController()
    const timer = setTimeout(() => ac.abort(), timeoutMs)
    try {
      const res = await fetch(url, {
        signal: ac.signal,
        headers: { accept: 'application/json', 'user-agent': UA },
      })
      const text = await res.text()
      let body
      try { body = JSON.parse(text) } catch {
        throw new Error(`unexpected non-JSON response (HTTP ${res.status}) from ${url}`)
      }
      // The API reports "not found" as 400 *or* 404 with an error object; a rate limit (429) or server error with one is not an answer — retry it.
      if (body?.error && res.status !== 429 && res.status < 500) return { ok: false, error: body.error }
      if (!res.ok) throw new Error(`${res.status} ${res.statusText} from ${url}`)
      return { ok: true, result: body.result }
    } catch (err) {
      lastErr = err
      if (attempt === retries) break
      await new Promise((r) => setTimeout(r, jitter(1000 * 2 ** attempt)))
    } finally {
      clearTimeout(timer)
    }
  }
  throw lastErr
}

/**
 * Resolve any user-supplied identifier to a Meson swap ID.
 * @param {string} query swap ID, encoded swap, or a source/destination tx hash
 * @returns {Promise<string>}
 */
async function resolveSwapId (query) {
  const q = String(query).trim()
  const res = await getJson(`${EXPLORER}/api/v1/search?q=${encodeURIComponent(q)}`)
  if (!res.ok || !res.result?.swapId) throw new SwapNotFound(q)
  return res.result.swapId
}

/** Fetch the raw swap record for a known swap ID. */
async function fetchSwap (swapId) {
  const res = await getJson(`${EXPLORER}/api/v1/swap/${encodeURIComponent(swapId)}`)
  if (!res.ok || !res.result) throw new SwapNotFound(swapId)
  return res.result
}

