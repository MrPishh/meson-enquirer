/** Steps whose transaction is on the target chain (Meson's docs: LP lock, release, unlock) — their hashes link to that chain's explorer. */
const TARGET_CHAIN_STEPS = ['LOCKED', 'RELEASED', 'UNLOCKED']

/** An API timestamp as a Date, or null when it is missing. */
const toDate = (v) => (v ? new Date(v) : null)

/** Turn one raw swap record (single, batch or address endpoint — all the same shape) into the flat, display-ready view. */
function toSwapView (raw) {
  const decoded = decodeEncodedSwap(raw.encoded)
  const [fromAddress, toAddress] = Array.isArray(raw.fromTo) ? raw.fromTo : [null, null]

  const srFee = BigInt(raw.srFee ?? 0)
  const lpFee = BigInt(raw.lpFee ?? 0)
  const totalFee = srFee + lpFee
  const received = decoded.amount - totalFee

  const events = (raw.events ?? []).map((e) => ({
    name: e.name,
    hash: e.hash,
    pending: Boolean(e.pending),
    // Per Meson's docs, LOCKED, RELEASED and UNLOCKED happen on the target ("out") chain; every other step (POSTED, BONDED, EXECUTED, CANCELLED…) on the source ("in") chain.
    url: txUrl(TARGET_CHAIN_STEPS.includes(String(e.name).split(':')[0].toUpperCase()) ? decoded.outChain : decoded.inChain, e.hash),
  }))

  return {
    swapId: raw._id,
    encoded: raw.encoded,
    status: deriveStatus(raw, decoded),

    from: {
      chain: chainName(decoded.inChain),
      chainId: chainId(decoded.inChain),
      token: tokenSymbol(decoded.inChain, decoded.inToken),
      address: fromAddress,
      addressUrl: addressUrl(decoded.inChain, fromAddress),
      amount: formatAmount(decoded.amount),
    },
    to: {
      chain: chainName(decoded.outChain),
      chainId: chainId(decoded.outChain),
      token: tokenSymbol(decoded.outChain, decoded.outToken),
      address: toAddress,
      addressUrl: addressUrl(decoded.outChain, toAddress),
      amount: formatAmount(received < 0n ? 0n : received),
    },

    fee: {
      service: formatAmount(srFee),
      lp: formatAmount(lpFee),
      total: formatAmount(totalFee),
    },

    requestedAt: toDate(raw.created),
    releasedAt: toDate(raw.released),
    expiresAt: decoded.expireTs ? new Date(decoded.expireTs * 1000) : null,

    events,
    explorerUrl: `${EXPLORER}/swap/${raw._id}`,
    // Names of this swap's chains Meson cannot reach right now — filled in by addChainHealth for unfinished swaps.
    troubledChains: [],
  }
}

