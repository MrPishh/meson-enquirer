/** At most one read of the live table per this long because of unknown chains or tokens, so a chain the explorer itself does not know yet cannot cause a read on every check. */
const UNKNOWN_REFRESH_GAP_MS = 10 * 60 * 1000

/** How long a lookup waits for that read before showing what it has; the read carries on, and the embed is corrected on the swap's next check. */
const REFRESH_WAIT_MS = 15 * 1000

/** Last read of the live table: when it started, and the read in progress. */
const presetRead = { at: 0, pending: null }

/**
 * Read Meson's live chain and token table and start using it, so chains and tokens added later need no code change or restart.
 * Never throws: on any failure the table in use stays as it is (logged).
 */
export function refreshPresets () {
  presetRead.at = Date.now()
  presetRead.pending ??= (async () => {
    try {
      const { added, relabelled } = mergeChains(await fetchLiveChains({ timeoutMs: config.mesonTimeoutMs }))
      if (added.length) console.log(`chain and token table: added ${added.join(', ')}`)
      if (relabelled.length) console.log(`chain and token table: ${relabelled.join(', ')}`)
    } catch (err) {
      console.error(`!! could not read Meson's chain and token table, keeping the current one — ${err.message}`)
    } finally {
      presetRead.pending = null
    }
  })()
  return presetRead.pending
}

/** Whether this raw record uses a chain or token the table does not know (a malformed record counts as known: viewOf deals with it). */
function usesUnknownName (raw) {
  try {
    const d = decodeEncodedSwap(raw.encoded)
    return !isKnownPair(d.inChain, d.inToken) || !isKnownPair(d.outChain, d.outToken)
  } catch {
    return false
  }
}

/**
 * Before showing swaps: if any uses an unknown chain or token, read the live table first, so the embed names it correctly the first time.
 * If it is still unknown afterwards, the embed shows `Unknown chain (0x…)` / `token#NN` rather than a guess, and a warning is logged.
 */
async function ensureNamesKnown (raws) {
  const unknown = raws.filter(usesUnknownName)
  if (!unknown.length || Date.now() - presetRead.at < UNKNOWN_REFRESH_GAP_MS) return
  let timer
  await Promise.race([refreshPresets(), new Promise((resolve) => { timer = setTimeout(resolve, REFRESH_WAIT_MS) })])
  clearTimeout(timer)
  const left = unknown.filter(usesUnknownName)
  if (left.length) console.error(`!! ${left.length} swap(s) use a chain or token not in Meson's table, e.g. ${left[0]._id}`)
}

/** Read the table shortly after startup, then every PRESETS_REFRESH_HOURS (jittered). 0 hours = only when a swap needs it. */
export function startPresetRefresh () {
  if (config.presetsRefreshMs <= 0) return
  const next = (ms) => setTimeout(() => refreshPresets().finally(() => next(jitter(config.presetsRefreshMs))), ms).unref()
  next(jitter(30 * 1000))
}

