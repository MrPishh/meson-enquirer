/**
 * Meson swap lookup.
 *
 * Three upstreams are in play, none needing an API key:
 *
 *  - explorer.meson.fi/api/v1/search?q=...          resolves a swap ID, an encoded swap, an EVM tx hash or a Solana signature to a swap ID.
 *  - explorer.meson.fi/api/v1/swap/<swapId>         one swap's addresses, fees, timestamps and encoded swap.
 *  - explorer.meson.fi/api/v1/address/<addr>/swap   every swap an address took part in (either side), paginated with ?page=&size=, same record shape as the single-swap endpoint.
 *
 * The *documented* relayer endpoints (relayer.meson.fi/api/v1/swap?hash= and /api/v1/swap/<id>) only return event hashes plus an `expired` flag — no chains, amount or addresses, and no address-history endpoint at all — so they cannot answer what a support ticket actually asks.
 * We use the explorer API throughout.
 */
