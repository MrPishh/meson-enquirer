/**
 * Look up a swap from anything a user might paste — swap ID, encoded swap, source or destination tx hash, Solana signature — and return a flat, display-ready object.
 * The explorer's search resolves all of them the same way, so there is no need to tell them apart.
 * @param {string} query
 */
export async function lookupSwap (query) {
  const q = String(query).trim()
  try {
    return await getSwap(await resolveSwapId(q))
  } catch (err) {
    if (err instanceof SwapNotFound) throw err
    // The explorer is down, not saying "not found": Meson's relayer (another host) may still know the swap. If it does not, the explorer's error stands, so the caller retries — the relayer cannot settle "not found" (it knows no wallets and fewer value shapes).
    const limited = await lookupOnRelayer(q).catch((e) => {
      console.error(`relayer stand-in for ${q} failed too — ${e.message}`)
      return null
    })
    if (!limited) throw err
    console.error(`explorer unavailable (${err.message}) — showing ${limited.swapId} with limited details from Meson's relayer`)
    return limited
  }
}

/** A swap by its known swap ID (one request — for a single lookup; re-checks of several swaps use getSwaps). */
async function getSwap (swapId) {
  const raw = await fetchSwap(swapId)
  await ensureNamesKnown([raw])
  const view = viewOf(raw)
  if (!view) throw new SwapNotFound(swapId)
  await addChainHealth([view])
  return view
}

/** Most swap IDs sent in one getSwaps request (20 checked against the live API, 2026-10-28). */
export const SWAP_BATCH_SIZE = 20

/** After the batch form has clearly stopped working, look swaps up one by one for this long, then try the batch again. */
const BATCH_PAUSE_MS = 60 * 60 * 1000

/** Until when the batch form is skipped (0 = in use). */
let batchPausedUntil = 0

/**
 * Several swaps by known swap ID in one request (what the background re-checks and restart recovery use), keyed by lower-case swap ID.
 * The explorer takes the IDs comma-separated (`/api/v1/swap/<id>,<id>`) and answers with an array of the same records as the single lookup — sorted, not in request order, duplicates merged, unknown IDs left out. Any ID the batch left out is double-checked on its own (below), so a missing key here really is "not found".
 * Pass at most SWAP_BATCH_SIZE IDs.
 * @param {string[]} swapIds
 * @returns {Promise<Map<string, ReturnType<typeof toSwapView>>>}
 */
export async function getSwaps (swapIds) {
  if (!swapIds.length) return new Map()
  // The batch form is not documented: if Meson changes it, it may quietly leave swaps out — or, if the route is removed, answer with an HTML 404 page (which getJson throws on, like an outage).
  // Either would stop every follow-up and drop swaps on recovery, so the batch stays the first choice and anything it does not deliver is looked up on its own (one request each).
  // Once it has clearly stopped working, it is skipped for BATCH_PAUSE_MS (no wasted request and retries every round), then tried again — so it is back in use as soon as Meson restores it.
  const batched = swapIds.length > 1 && Date.now() >= batchPausedUntil
  let list = []
  let batchFailed = false
  if (batched || swapIds.length === 1) {
    try {
      const res = await getJson(`${EXPLORER}/api/v1/swap/${swapIds.map(encodeURIComponent).join(',')}`)
      // One ID is answered with the swap itself (or a "not found" error), not an array.
      list = !res.ok ? [] : Array.isArray(res.result) ? res.result : res.result ? [res.result] : []
    } catch (err) {
      // A real outage fails the single lookups below too, and that error is what the caller sees (and retries).
      if (swapIds.length === 1) throw err // a one-ID batch is the single lookup
      batchFailed = true
      console.error(`batch lookup of ${swapIds.length} swaps failed (${err.message}) — trying them one by one`)
    }
  }
  await ensureNamesKnown(list)
  const views = list.map(viewOf).filter(Boolean)
  await addChainHealth(views)
  const found = new Map(views.map((v) => [v.swapId.toLowerCase(), v]))

  // Only a swap the single lookup cannot find either is truly missing.
  const missing = [...new Set(swapIds.map((id) => id.toLowerCase()))].filter((id) => !found.has(id))
  let recovered = 0
  for (const id of missing) {
    try {
      found.set(id, await getSwap(id))
      recovered++
    } catch (err) {
      if (!(err instanceof SwapNotFound)) throw err
    }
  }
  // Swaps the batch should have delivered were found one by one — whether it failed outright or left them out, it has stopped working while Meson itself works.
  if (batched && recovered) {
    batchPausedUntil = Date.now() + BATCH_PAUSE_MS
    console.error(`batch lookup ${batchFailed ? 'failed' : `left out ${recovered} of ${swapIds.length} swap(s) that exist`} while single lookups work — Meson may have changed /api/v1/swap/<id>,<id>; looking swaps up one by one for the next ${BATCH_PAUSE_MS / 60000} minutes, then trying the batch again`)
  }
  return found
}

// =============================================================================
//   Relayer stand-in
// =============================================================================

/**
 * Look a swap up on Meson's relayer — only while the explorer is down (lookupSwap).
 * `/api/v1/swap/<x>` takes a swap ID or an encoded swap, `?hash=` a source or destination transaction hash; a 0x + 64 hex value can be any of them, so it may take both. Null when the relayer does not know it.
 */
async function lookupOnRelayer (query) {
  const paths = /^0x[0-9a-fA-F]{64}$/.test(query) ? [`/api/v1/swap/${query}`, `/api/v1/swap?hash=${query}`] : [`/api/v1/swap?hash=${encodeURIComponent(query)}`]
  for (const path of paths) {
    const res = await getJson(RELAYER + path)
    if (res.ok && res.result?.swap?.id) return limitedView(res.result)
  }
  return null
}

/**
 * A relayer answer (`{EXECUTED: <hash>, RELEASED: <hash>, …, swap: {id, encoded, to: {amount}}}`) as a swap view flagged `limited`.
 * Chains, tokens, the amount and the deadline come from the encoded swap as usual, and the status from the explorer's own function (explorerStatus) over the successful steps — so it can miss Failed and "confirming", and a swap may read as further along than the explorer would show — which is why buildSwapEmbed shows no status for it and watchSwap posts no follow-up from it. There are no wallet addresses and no request time; the fee is only known as a total.
 */
async function limitedView (result) {
  const raw = {
    _id: result.swap.id,
    encoded: result.swap.encoded,
    // Steps are the upper-case keys holding a hash; `swap` and `expired` are not steps.
    events: Object.entries(result).filter(([k, v]) => /^[A-Z]+$/.test(k) && typeof v === 'string' && v).map(([name, hash]) => ({ name, hash })),
  }
  await ensureNamesKnown([raw])
  const view = toSwapView(raw)
  const received = parseAmount(result.swap.to?.amount)
  const sent = decodeEncodedSwap(raw.encoded).amount
  if (received !== null) {
    view.to.amount = formatAmount(received)
    view.fee = { service: null, lp: null, total: formatAmount(sent - received) }
  } else {
    view.fee = { service: null, lp: null, total: null }
  }
  view.limited = true
  await addChainHealth([view])
  return view
}

