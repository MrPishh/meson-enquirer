/**
 * Watches the Meson explorer's own status function — the one `explorerStatus` (src/meson.js) is a line-for-line port of — and warns in the log when Meson changes it, so the port is redone before ticket statuses drift from the explorer.
 *
 * The explorer is minified: its variable names (`e`, `t`, `r`…) can change on every deploy without any logic change, so the function is compared by a fingerprint with those short names blanked out — only a real change (status order, strings, conditions, numbers) alters it.
 * Checked at startup and every EXPLORER_CHECK_HOURS; never throws and never affects ticket handling. `npm run check-explorer` runs the same check from the terminal and prints the function for re-porting.
 */
