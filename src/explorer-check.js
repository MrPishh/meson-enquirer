import { createHash } from 'node:crypto'
import { config } from './config.js'
import { EXPLORER, jitter } from './meson.js'

// =============================================================================
//   Fingerprint
// =============================================================================

/**
 * Fingerprint of the explorer status function that `explorerStatus` matches (checked 2026-10-28 on 2000 real swaps).
 * When the check reports a change: re-port the function (CONTEXT.md § Status derivation), re-verify on real swaps, then put the new fingerprint here.
 */
export const PORTED_FINGERPRINT = '1ad3c072881a3ce2'

/** Where the function starts in the bundle: the explorer's step-rank array. */
const START = '["FAILED","PENDING","REQUESTING"'

/** Where it ends: its last line, `…:l?"LOCKED":c}`. */
const END = /\?"LOCKED":[\w$]+\}/g

/** JavaScript keywords short enough to look minified — kept, so they still count in the fingerprint. */
const KEYWORDS = new Set(['if', 'in', 'do', 'of'])

/** The function's text with minified (1–2 character) names blanked, strings and keywords kept. */
const normalise = (code) => code.replace(/"(?:[^"\\]|\\.)*"|[A-Za-z_$][\w$]*/g, (t) => (t.startsWith('"') || t.length > 2 || KEYWORDS.has(t) ? t : '_'))

/** The status function in one bundle chunk, or null if the chunk does not contain it. */
function extract (js) {
  const start = js.indexOf(START)
  if (start === -1) return null
  END.lastIndex = start
  const end = END.exec(js)
  return end ? js.slice(start, end.index + end[0].length) : null
}

// =============================================================================
//   Fetching
// =============================================================================

/** The chunk that held the function last time — tried first, so a check is usually two requests. */
let lastChunk = null

/** GET a URL as text (bounded by MESON_TIMEOUT_SECONDS). */
async function getText (url) {
  const ac = new AbortController()
  const timer = setTimeout(() => ac.abort(), config.mesonTimeoutMs)
  try {
    const res = await fetch(url, { signal: ac.signal, headers: { 'user-agent': 'meson-ticket-bot' } })
    if (!res.ok) throw new Error(`HTTP ${res.status} from ${url}`)
    return await res.text()
  } finally {
    clearTimeout(timer)
  }
}

/**
 * Find the explorer's status function in its current bundle and fingerprint it.
 * @returns {Promise<{fingerprint: string, matches: boolean, chunk: string, code: string}>}
 * @throws if the explorer cannot be reached or no chunk contains the function (bundle layout changed)
 */
export async function checkExplorerStatus () {
  const html = await getText(`${EXPLORER}/`)
  const chunks = [...new Set([...html.matchAll(/\/_next\/static\/chunks\/[\w/.-]+\.js/g)].map((m) => m[0]))]
  if (lastChunk && chunks.includes(lastChunk)) chunks.unshift(lastChunk)
  for (const chunk of new Set(chunks)) {
    const code = extract(await getText(EXPLORER + chunk))
    if (!code) continue
    lastChunk = chunk
    const fingerprint = createHash('sha256').update(normalise(code)).digest('hex').slice(0, 16)
    return { fingerprint, matches: fingerprint === PORTED_FINGERPRINT, chunk, code }
  }
  throw new Error(`the status function was not found in any of the explorer's ${chunks.length} chunks — the bundle layout changed`)
}

// =============================================================================
//   Schedule
// =============================================================================

/** Run one check and log the result: quiet line when unchanged, a loud warning when changed or not found. */
async function runCheck () {
  try {
    const r = await checkExplorerStatus()
    if (r.matches) console.log(`explorer status function unchanged (${r.fingerprint})`)
    else console.error(`!! Meson's explorer changed its status function (${r.fingerprint}, port matches ${PORTED_FINGERPRINT}) — ticket statuses may no longer match the explorer. Run \`npm run check-explorer\`, re-port explorerStatus in src/meson.js (CONTEXT.md § Status derivation), then update PORTED_FINGERPRINT.`)
  } catch (err) {
    console.error(`!! explorer status check failed — ${err.message}`)
  }
}

/** Check once shortly after startup, then every EXPLORER_CHECK_HOURS (jittered). 0 hours = off. */
export function startExplorerCheck () {
  if (config.explorerCheckMs <= 0) return
  const next = (ms) => setTimeout(() => runCheck().finally(() => next(jitter(config.explorerCheckMs))), ms).unref()
  next(jitter(60 * 1000))
}
