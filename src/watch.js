/**
 * Keeps a posted swap current until it finishes.
 *
 * Right after a swap's details embed is posted, watchSwap replies with either the closing note (already finished: Done / Released / Cancelled) or the ⏳ "being processed" line (still moving normally), then re-polls in the background.
 * On every status or event change it edits the details embed in place (silent — an edit notifies nobody); once the swap is finished it replies to that embed with the closing note, which is what the user actually gets notified about, and deletes its ⏳ line.
 * syncFollowUps keeps a swap's ⏳ / closing note labelled "Swap #n" and drops "closed soon" when another swap joins the ticket.
 *
 * Expired, Unlocked and Failed keep being watched — a failed step is retried or resolved by the team, and every swap ends finished.
 * A swap can sit in "Releasing" for many hours and Releasing never turns into Expired, so the time limit must stay generous.
 * Polling backs off with age to keep requests to Meson low.
 *
 * In-memory only: a bot restart drops every watch in flight, and recover.js resumes them on startup (watchSwap `resumed`). A resumed watch's SWAP_WATCH_MAX_HOURS counts from the restart.
 */
