/** The details embed for a ticket's swap entry, with its "#n" if there are several. */
export const detailsEmbed = (t, entry, sourceNote = 'auto-detected from this ticket') =>
  buildSwapEmbed(entry.latest, { serial: serialOf(t, entry), sourceNote })

/**
 * Bring a swap's ⏳ and closing message in line with the ticket as it is now: its "Swap #n", and whether "ticket will be closed soon" still holds.
 * Called for the earlier swaps whenever a new one is posted (postSwap), and after each send in case a swap arrived meanwhile; edits only what changed, silently.
 * @param {import('./ticket-state.js').Ticket} t
 * @param {import('./ticket-state.js').SwapEntry} entry
 */
export async function syncFollowUps (t, entry) {
  const processing = buildProcessingMessage({ serial: serialOf(t, entry) })
  if (entry.processing && entry.processing.content !== processing) {
    entry.processing = await entry.processing.edit({ content: processing }).catch(() => entry.processing)
  }
  // "Closed soon" is only ever dropped here, never added: it belongs on the closing message of the swap that finished last.
  const opts = outcomeOpts(t, entry)
  const outcome = entry.outcome && buildOutcomeMessage(entry.latest, { ...opts, closingSoon: opts.closingSoon && entry.outcome.content.includes(CLOSING_SOON) })
  if (entry.outcome && outcome && entry.outcome.content !== outcome) {
    entry.outcome = await entry.outcome.edit({ content: outcome }).catch(() => entry.outcome)
  }
}

/**
 * Follow a just-posted swap: post its closing note if it is already finished; otherwise post its ⏳ (if it is moving normally) and start re-checking it.
 * `resumed`: the swap was rebuilt after a restart (recover.js) — its ⏳ / closing message already exist, so none is posted again; the embed is brought up to date, and a swap that finished while the bot was down gets its closing message now.
 * @param {import('./ticket-state.js').Ticket} t
 * @param {import('./ticket-state.js').SwapEntry} entry
 * @param {{resumed?: boolean}} [opts]
 */
export async function watchSwap (t, entry, { resumed = false } = {}) {
  const channel = entry.message.channel
  const key = `${channel.id}:${entry.swapId}`
  watchers.delete(key)

  if (resumed) {
    if (entry.outcome) return // closed before the restart — nothing left to follow
    await entry.message.edit({ embeds: [detailsEmbed(t, entry, 'auto-detected from this ticket · auto-updated')] }).catch(() => {})
  }

  const outcome = buildOutcomeMessage(entry.latest, outcomeOpts(t, entry))
  if (outcome) {
    // Kept on the entry so a later swap can renumber it / drop its "closed soon" (syncFollowUps).
    entry.outcome = await quietReply(entry.message, { content: outcome })
    // Only a resumed swap can have a ⏳ here (it finished while the bot was down).
    await entry.processing?.delete().catch(() => {})
    entry.processing = null
    await syncFollowUps(t, entry)
    console.log(`#${channel.name}: ${entry.swapId} already ${entry.latest.status.label} — posted outcome`)
    return
  }
  // Failed / Expired / Unlocked / stuck (status.ok false) will not "complete shortly": no ⏳ — and a resumed swap that became one while the bot was down loses the ⏳ it had. A resumed swap still moving normally keeps the ⏳ it has (or had).
  if (entry.latest.status.ok && !resumed) await postProcessing(t, entry)
  if (!entry.latest.status.ok && entry.processing) await withdrawProcessing(entry, channel, entry.latest)
  if (config.watchIntervalMs <= 0) return

  // Checked from the next round on, together with every other due swap.
  watchers.set(key, { key, t, entry, channel, startedAt: Date.now(), last: fingerprint(entry.latest), dueAt: Date.now() })
  scheduleRound()
}

/** Cancel every watch in a channel — called when a ticket channel is deleted. */
export function stopWatchingChannel (channelId) {
  for (const key of watchers.keys()) {
    if (key.startsWith(`${channelId}:`)) watchers.delete(key)
  }
}
