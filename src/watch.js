import { config } from './config.js'
import { getSwaps, SWAP_BATCH_SIZE, jitter } from './meson.js'
import { buildSwapEmbed, buildOutcomeMessage, buildProcessingMessage, CLOSING_SOON } from './render.js'
import { rememberSwap, serialOf, outcomeOpts } from './ticket-state.js'
import { quietReply, CHANNEL_GONE } from './discord-util.js'

// =============================================================================
//   Polling
// =============================================================================

/**
 * Every watched swap, keyed `${channelId}:${swapId}`: what a check round needs to re-check it, and when it is next due.
 * @type {Map<string, {key: string, t: import('./ticket-state.js').Ticket, entry: import('./ticket-state.js').SwapEntry, channel: import('discord.js').TextBasedChannel, startedAt: number, last: string, dueAt: number}>}
 */
const watchers = new Map()

/** Timer of the next check round (null while none is planned or one is running). */
let roundTimer = null
let roundRunning = false

/** Anything that should cause an embed edit: status (and whether it is stuck), each event's state, and the network notice. */
const fingerprint = (swap) =>
  [swap.status.label + swap.status.star + (swap.status.stuck ? ':stuck' : ''), ...swap.events.map((e) => `${e.name}:${e.pending}`), `notice:${swap.troubledChains.join(',')}`].join('|')

/** Poll fast while a swap is likely to move, then back off (the SWAP_WATCH_* settings) — never stopping. */
function watchDelay (ageMs) {
  if (ageMs < config.watchSlowerAfterMs) return config.watchIntervalMs
  if (ageMs < config.watchSlowestAfterMs) return config.watchSlowerIntervalMs
  if (ageMs < config.watchLongAfterMs) return config.watchSlowestIntervalMs
  return config.watchLongIntervalMs
}

/** How old a watched swap is: since it was requested (from Meson), or since the bot began watching it if that is unknown. */
const ageOf = (w) => Date.now() - (w.entry.latest.requestedAt?.getTime() ?? w.startedAt)

/**
 * When a just-checked swap is next due.
 * Half a round is taken off because a due swap waits for the next round (rounds come every SWAP_WATCH_INTERVAL_SECONDS, jittered) — so on average it is checked at its own interval.
 */
const nextDue = (w) => Date.now() + jitter(watchDelay(ageOf(w))) - config.watchIntervalMs / 2

/** Plan the next check round, unless one is planned or running, or nothing is watched. */
function scheduleRound () {
  if (roundTimer || roundRunning || !watchers.size) return
  roundTimer = setTimeout(runRound, jitter(config.watchIntervalMs))
}

/**
 * One check round: every watched swap that is due is re-checked together — one Meson request per SWAP_BATCH_SIZE swaps (getSwaps), however many tickets they are in — instead of one request per swap.
 * A failed request (Meson down, rate limit) or a swap missing from the answer just waits for its next due time; it never ends the watch.
 */
async function runRound () {
  roundTimer = null
  roundRunning = true
  try {
    const now = Date.now()
    const due = []
    for (const w of watchers.values()) if (w.dueAt <= now) due.push(w)
    const ids = [...new Set(due.map((w) => w.entry.swapId.toLowerCase()))]
    for (let i = 0; i < ids.length; i += SWAP_BATCH_SIZE) {
      const batch = ids.slice(i, i + SWAP_BATCH_SIZE)
      let found
      try {
        found = await getSwaps(batch)
      } catch (err) {
        console.error(`re-check of ${batch.length} swap(s) failed, will try again —`, err.message)
      }
      for (const w of due) {
        const id = w.entry.swapId.toLowerCase()
        if (!batch.includes(id) || watchers.get(w.key) !== w) continue
        const latest = found?.get(id)
        if (found && !latest) console.error(`#${w.channel.name}: ${w.entry.swapId} missing from Meson's answer, will try again`)
        if (latest) await applyCheck(w, latest)
        if (watchers.get(w.key) === w) w.dueAt = nextDue(w)
      }
    }
  } catch (err) {
    console.error('check round failed —', err.message)
  } finally {
    roundRunning = false
    scheduleRound()
  }
}

/** Act on one fresh look at a watched swap: edit the embed if it changed, post the closing message and stop once it is finished. */
async function applyCheck (w, latest) {
  const { t, entry, channel } = w
  try {
    entry.latest = latest
    rememberSwap(t, latest) // the release hash only appears later
    const next = fingerprint(latest)
    if (next !== w.last) {
      w.last = next
      // Staff may have deleted the details message — not a reason to stop.
      await entry.message.edit({ embeds: [detailsEmbed(t, entry, 'auto-detected from this ticket · auto-updated')] })
        .catch(() => {})
      console.log(`#${channel.name}: ${entry.swapId} is now ${latest.status.label} — updated details`)
    }
    const done = buildOutcomeMessage(latest, outcomeOpts(t, entry))
    if (done) {
      entry.outcome = await quietReply(entry.message, { content: done })
      // Staff may have deleted it already — not an error.
      await entry.processing?.delete().catch(() => {})
      entry.processing = null
      await syncFollowUps(t, entry)
      stopWatch(w, `${latest.status.label} — posted outcome`)
    } else if (!latest.status.ok && entry.processing) {
      await withdrawProcessing(entry, channel, latest)
    }
  } catch (err) {
    if (CHANNEL_GONE.has(err.code)) return stopWatch(w, 'ticket closed')
    // Discord hiccup: keep following — the next check is due anyway.
    console.error(`#${channel.name}: re-check of ${entry.swapId} failed, will try again —`, err.message)
  }
}

/**
 * Post a swap's ⏳ "being processed" reply.
 * Kept on the entry so it can be renumbered (postSwap) and deleted once the closing message is posted — keeps the ticket clean.
 */
async function postProcessing (t, entry) {
  entry.processing = await quietReply(entry.message, { content: buildProcessingMessage({ serial: serialOf(t, entry) }) })
  // A 2nd swap posted while this was sending found no ⏳ to renumber — catch up.
  await syncFollowUps(t, entry)
}

/**
 * Remove a swap's ⏳ once it is no longer moving normally (stuck, Expired, Failed, Unlocked): its "will be completed shortly" promise no longer holds, and the embed's description now says what is going on.
 */
async function withdrawProcessing (entry, channel, latest) {
  // Staff may have deleted it already — not an error.
  await entry.processing.delete().catch(() => {})
  entry.processing = null
  console.log(`#${channel.name}: ${entry.swapId} is ${latest.status.stuck ? 'stuck' : latest.status.label} — removed its ⏳`)
}

/** End one watch (logged). */
function stopWatch (w, why) {
  if (watchers.get(w.key) === w) watchers.delete(w.key)
  console.log(`#${w.channel.name}: stopped watching ${w.entry.swapId} (${why})`)
}

