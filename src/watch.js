/**
 * Every watched swap, keyed `${channelId}:${swapId}`: what a check round needs to re-check it, and when it is next due.
 * @type {Map<string, {key: string, t: import('./ticket-state.js').Ticket, entry: import('./ticket-state.js').SwapEntry, channel: import('discord.js').TextBasedChannel, startedAt: number, last: string, dueAt: number}>}
 */
const watchers = new Map()

/** Timer of the next check round (null while none is planned or one is running). */
let roundTimer = null
let roundRunning = false

/** How long a swap waits after Discord refused a post (Missing Permissions…) before trying again: it stays followed in case access returns, without repeating the refusal every check. */
const REFUSED_PAUSE_MS = 60 * 60 * 1000

/** Anything that should cause an embed edit: status (and whether it is stuck), each event's state, the network notice, the chain and token names (a chain or token that was unknown when posted gets its name once the live table has it), and whether it came from the relayer stand-in (replaced by the full details once the explorer is back). */
const fingerprint = (swap) =>
  [swap.status.label + swap.status.star + (swap.status.stuck ? ':stuck' : ''), ...swap.events.map((e) => `${e.name}:${e.pending}`), `notice:${swap.troubledChains.join(',')}`, `names:${swap.from.chain}/${swap.from.token}/${swap.to.chain}/${swap.to.token}`, swap.limited ? 'limited' : 'full'].join('|')

/** Poll fast while a swap is likely to move, then back off (the SWAP_WATCH_* settings) — never stopping. */
function watchDelay (ageMs) {
  if (ageMs < config.watchSlowerAfterMs) return config.watchIntervalMs
  if (ageMs < config.watchSlowestAfterMs) return config.watchSlowerIntervalMs
  if (ageMs < config.watchLongAfterMs) return config.watchSlowestIntervalMs
  return config.watchLongIntervalMs
}

/** How old a watched swap is: since it was requested (from Meson), or since the bot began watching it if that is unknown. */
const ageOf = (w) => Date.now() - (w.entry.latest.requestedAt?.getTime() ?? w.startedAt)

/**
 * When a just-checked swap is next due: by its age (watchDelay), or every SWAP_WATCH_LONG_INTERVAL_MINUTES once its closing message is up — a cancelled swap is then only watched in case Meson releases it after all, which is rare. (Not before: a finished swap whose embed edit or closing message failed is retried at its usual pace.)
 * Half a round is taken off because a due swap waits for the next round (rounds come every SWAP_WATCH_INTERVAL_SECONDS, jittered) — so on average it is checked at its own interval.
 */
const nextDue = (w) => Date.now() + jitter(w.entry.outcome ? config.watchLongIntervalMs : watchDelay(ageOf(w))) - config.watchIntervalMs / 2

/** Plan the next check round, unless one is planned or running, or nothing is watched. */
function scheduleRound () {
  if (roundTimer || roundRunning || !watchers.size) return
  roundTimer = setTimeout(runRound, jitter(config.watchIntervalMs))
}

/**
 * The watched swaps to check in a round starting at `now`: every one that is due, and with SWAP_WATCH_BUNDLE the others as well, soonest due first, as far as they fit in the spare places of the requests the due ones need — so bundling never adds a request.
 * A swap paused after Discord refused a post is not pulled in early, so the pause holds.
 */
function pickForRound (now) {
  const due = []
  const rest = []
  for (const w of watchers.values()) (w.dueAt <= now ? due : rest).push(w)
  if (!config.watchBundle || !due.length) return due
  const ids = new Set(due.map((w) => w.entry.swapId.toLowerCase()))
  const room = Math.ceil(ids.size / SWAP_BATCH_SIZE) * SWAP_BATCH_SIZE
  for (const w of rest.sort((a, b) => a.dueAt - b.dueAt)) {
    if (w.refusedUntil > now) continue
    const id = w.entry.swapId.toLowerCase()
    if (!ids.has(id)) {
      if (ids.size >= room) continue
      ids.add(id)
    }
    due.push(w)
  }
  return due
}

/**
 * One check round: every watched swap that is due (with SWAP_WATCH_BUNDLE, every watched swap that fits — pickForRound) is re-checked together — one Meson request per SWAP_BATCH_SIZE swaps (getSwaps), however many tickets they are in — instead of one request per swap.
 * A failed request (Meson down, rate limit) or a swap missing from the answer just waits for its next due time; it never ends the watch.
 */
async function runRound () {
  roundTimer = null
  roundRunning = true
  try {
    const due = pickForRound(Date.now())
    const ids = [...new Set(due.map((w) => w.entry.swapId.toLowerCase()))]
    for (let i = 0; i < ids.length; i += SWAP_BATCH_SIZE) {
      const batch = ids.slice(i, i + SWAP_BATCH_SIZE)
      let found
      try {
        found = await getSwaps(batch)
      } catch (err) {
        console.error(`re-check of ${batch.length} swap(s) failed, will try again —`, err.message)
      }
      for (const w of due) {
        const id = w.entry.swapId.toLowerCase()
        if (!batch.includes(id) || watchers.get(w.key) !== w) continue
        const latest = found?.get(id)
        if (found && !latest) console.error(`#${w.channel.name}: ${w.entry.swapId} missing from Meson's answer, will try again`)
        if (latest) await applyCheck(w, latest)
        if (watchers.get(w.key) === w) w.dueAt = Math.max(nextDue(w), w.refusedUntil)
      }
    }
  } catch (err) {
    console.error('check round failed —', err.message)
  } finally {
    roundRunning = false
    scheduleRound()
  }
}

/** Act on one fresh look at a watched swap: edit the embed if it changed, then bring its replies in line — the closing message once it is finished (replaced if Meson changed the outcome, syncOutcome), else its ⏳ / 🔎 — and the ticket's wallet list. */
async function applyCheck (w, latest) {
  const { t, entry, channel } = w
  try {
    entry.latest = latest
    rememberSwap(t, latest) // the release hash only appears later
    const next = fingerprint(latest)
    if (next !== w.last) {
      // Remembered as shown only once the edit worked, so a failed one (Discord hiccup) is tried again at the next check — or the embed could show an old status next to a newer closing message.
      // Discord refusing it (staff deleted the details message, lost permissions) is not retried: repeating would only repeat the refusal. Nor is it a reason to stop. But a ticket that is gone is: its delete event may have been missed during a disconnect.
      let retry = false
      const result = await entry.message.edit({ embeds: [detailsEmbed(t, entry, 'auto-detected from this ticket · auto-updated')] })
        .then(() => 'updated details', (err) => {
          if (CHANNEL_GONE.has(err.code)) throw err
          retry = !discordRefused(err)
          return `details not updated, ${retry ? 'will try again' : 'Discord refused'} (${err.message})`
        })
      if (!retry) w.last = next
      console.log(`#${channel.name}: ${entry.swapId} is now ${latest.status.label} — ${result}`)
      // The embed first, then what follows from it: a closing message must not go up while the embed still shows the old status.
      if (retry) return
    }
    const finished = await syncOutcome(t, entry, channel)
    if (!finished) {
      if (!latest.status.ok) entry.processingOwed = false
      await syncSupport(t, entry, channel)
      if (latest.status.ok && entry.processingOwed) {
        await postProcessing(t, entry)
        entry.processingOwed = false
      }
    }
    await syncWalletList(t)
    // Completed (Done / Released) is final. Cancelled is not quite: Meson has released a swap after cancelling it (2026-11-24), so a cancelled swap stays watched until its ticket is deleted.
    if (finished && outcomeKind(latest.status) === 'completed') stopWatch(w, `${latest.status.label} — completed`)
  } catch (err) {
    if (CHANNEL_GONE.has(err.code)) return stopWatch(w, 'ticket closed')
    if (discordRefused(err)) w.refusedUntil = Date.now() + REFUSED_PAUSE_MS
    // Discord hiccup: keep following — the next check is due anyway.
    console.error(`#${channel.name}: re-check of ${entry.swapId} failed, will try again${discordRefused(err) ? ` in ${REFUSED_PAUSE_MS / 60000} minutes` : ''} —`, err.message)
  }
}

/**
 * Bring a swap's closing message in line with its status: post it once the swap is finished (Done / Released → ✅, Cancelled → ↩️).
 * If Meson changed the outcome of a swap already closed (seen 2026-11-24: Cancelled, then released → Done), the old closing message would say the wrong thing, so it is deleted and the new outcome posted as a fresh reply — the user is notified of it, as of the first; a swap moving again gets its ⏳ / 🔎 instead (`processingOwed`, syncSupport).
 * @returns {Promise<boolean>} whether the swap is finished, with its closing message up
 */
async function syncOutcome (t, entry, channel) {
  const now = outcomeKind(entry.latest.status)
  if (entry.outcome) {
    const posted = readOutcomeKind(entry.outcome.content)
    if (posted === now) return true
    await entry.outcome.delete().catch(() => {}) // staff may have deleted it already
    entry.outcome = null
    if (!now) entry.processingOwed = true
    console.log(`#${channel.name}: ${entry.swapId} was ${posted}, is now ${entry.latest.status.label} — closing message removed`)
    // Another swap's closing message may say "closed soon" only while this one is finished.
    for (const e of t.swaps) if (e !== entry) await syncFollowUps(t, e)
  }
  if (!now) return false
  await postClosing(t, entry, buildOutcomeMessage(entry.latest, outcomeOpts(t, entry)))
  console.log(`#${channel.name}: ${entry.swapId} is ${entry.latest.status.label} — posted its closing message`)
  // "Closed soon" belongs only on the closing message of the swap that finished last — which a replaced one can now be.
  if (entry.outcome.content?.includes(CLOSING_SOON)) {
    for (const e of t.swaps) {
      if (e === entry || !e.outcome?.content?.includes(CLOSING_SOON)) continue
      const content = buildOutcomeMessage(e.latest, { serial: serialOf(t, e), kind: readOutcomeKind(e.outcome.content), closingSoon: false })
      e.outcome = await e.outcome.edit({ content }).catch(() => e.outcome)
    }
  }
  return true
}

/**
 * Post a swap's closing message and take down its ⏳ and 🔎.
 * Kept on the entry so a later swap can renumber it / drop its "closed soon" (syncFollowUps).
 */
async function postClosing (t, entry, text) {
  entry.outcome = await quietReply(entry.message, { content: text })
  // Staff may have deleted them already — not an error.
  await entry.processing?.delete().catch(() => {})
  entry.processing = null
  await entry.support?.delete().catch(() => {})
  entry.support = null
  await syncFollowUps(t, entry)
}

/**
 * Post a swap's ⏳ "being processed" reply.
 * Kept on the entry so it can be renumbered (postSwap) and deleted once the closing message is posted — keeps the ticket clean.
 */
async function postProcessing (t, entry) {
  entry.processing = await quietReply(entry.message, { content: buildProcessingMessage({ serial: serialOf(t, entry) }) })
  // A 2nd swap posted while this was sending found no ⏳ to renumber — catch up.
  await syncFollowUps(t, entry)
}

/**
 * Remove a swap's ⏳ when it cannot be turned into the 🔎 (syncSupport): one is already up, or following is switched off and nothing would ever update it. Its "will be completed shortly" promise no longer holds.
 */
async function withdrawProcessing (entry, channel, latest) {
  // Staff may have deleted it already — not an error.
  await entry.processing.delete().catch(() => {})
  entry.processing = null
  console.log(`#${channel.name}: ${entry.swapId} is ${latest.status.stuck ? 'stuck' : latest.status.label} — removed its ⏳`)
}

/**
 * Bring a swap's status reply in line with its status: the ⏳ is edited into the 🔎 while the support team has to step in (silent, like every edit), reworded if the reason changes, and edited back into the ⏳ once the swap moves normally again.
 * If there is nothing to edit — no reply yet, or staff deleted it — a new one is posted (the 🔎 now; the ⏳ through `processingOwed`). A failed post needs no bookkeeping: the status still calls for the reply at the next check.
 */
async function syncSupport (t, entry, channel) {
  const { supportNote, stuck, label } = entry.latest.status
  const serial = serialOf(t, entry)
  if (supportNote) {
    const text = buildSupportMessage(supportNote, { serial })
    if (entry.processing && !entry.support) {
      entry.support = await entry.processing.edit({ content: text }).catch(() => null)
      // Not edited, and a new 🔎 follows below: make sure no ⏳ stays up promising completion next to it (staff may have deleted it already — not an error).
      if (!entry.support) await entry.processing.delete().catch(() => {})
      entry.processing = null
      if (entry.support) console.log(`#${channel.name}: ${entry.swapId} is ${stuck ? 'stuck' : label} — changed its ⏳ to 🔎`)
    } else if (entry.processing) {
      await withdrawProcessing(entry, channel, entry.latest)
    }
    if (!entry.support) {
      entry.support = await quietReply(entry.message, { content: text })
      console.log(`#${channel.name}: ${entry.swapId} is ${stuck ? 'stuck' : label} — posted its 🔎`)
    }
  } else if (entry.support) {
    const back = entry.processing ? null : await entry.support.edit({ content: buildProcessingMessage({ serial }) }).catch(() => null)
    if (back) entry.processing = back
    else {
      // Not edited (or a ⏳ is up already): no 🔎 stays up next to the ⏳.
      await entry.support.delete().catch(() => {})
      if (!entry.processing) entry.processingOwed = true
    }
    entry.support = null
    console.log(`#${channel.name}: ${entry.swapId} is moving again — its 🔎 is gone`)
  }
  await syncFollowUps(t, entry)
}

/** End one watch (logged). */
function stopWatch (w, why) {
  if (watchers.get(w.key) === w) watchers.delete(w.key)
  console.log(`#${w.channel.name}: stopped watching ${w.entry.swapId} (${why})`)
}

