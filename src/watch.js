import { config } from './config.js'
import { getSwap } from './meson.js'
import { buildSwapEmbed, buildOutcomeMessage, buildProcessingMessage, CLOSING_SOON } from './render.js'
import { rememberSwap, serialOf, outcomeOpts } from './ticket-state.js'
import { quietReply, CHANNEL_GONE } from './discord-util.js'

// =============================================================================
//   Polling
// =============================================================================

/**
 * Pending re-check per watched swap, keyed `${channelId}:${swapId}`.
 * @type {Map<string, NodeJS.Timeout>}
 */
const watchers = new Map()

/** Anything that should cause an embed edit: status plus each event's state. */
const fingerprint = (swap) =>
  [swap.status.label + swap.status.star, ...swap.events.map((e) => `${e.name}:${e.pending}`)].join('|')

/** Poll fast while a swap is likely to move, then back off (the SWAP_WATCH_* settings). */
function watchDelay (elapsedMs) {
  if (elapsedMs < config.watchSlowerAfterMs) return config.watchIntervalMs
  if (elapsedMs < config.watchSlowestAfterMs) return config.watchSlowerIntervalMs
  return config.watchSlowestIntervalMs
}

// =============================================================================
//   Watch lifecycle
// =============================================================================

/** The details embed for a ticket's swap entry, with its "#n" if there are several. */
export const detailsEmbed = (t, entry, sourceNote = 'auto-detected from this ticket') =>
  buildSwapEmbed(entry.latest, { serial: serialOf(t, entry), sourceNote })

/**
 * Bring a swap's ⏳ and closing message in line with the ticket as it is now: its "Swap #n", and whether "ticket will be closed soon" still holds.
 * Called for the earlier swaps whenever a new one is posted (postSwap), and after each send in case a swap arrived meanwhile; edits only what changed, silently.
 * @param {import('./ticket-state.js').Ticket} t
 * @param {import('./ticket-state.js').SwapEntry} entry
 */
export async function syncFollowUps (t, entry) {
  const processing = buildProcessingMessage({ serial: serialOf(t, entry) })
  if (entry.processing && entry.processing.content !== processing) {
    entry.processing = await entry.processing.edit({ content: processing }).catch(() => entry.processing)
  }
  // "Closed soon" is only ever dropped here, never added: it belongs on the closing message of the swap that finished last.
  const opts = outcomeOpts(t, entry)
  const outcome = entry.outcome && buildOutcomeMessage(entry.latest, { ...opts, closingSoon: opts.closingSoon && entry.outcome.content.includes(CLOSING_SOON) })
  if (entry.outcome && outcome && entry.outcome.content !== outcome) {
    entry.outcome = await entry.outcome.edit({ content: outcome }).catch(() => entry.outcome)
  }
}

/**
 * Post the first follow-up for a just-posted swap and, if it is not finished, start re-checking it.
 * `resumed`: the swap was rebuilt after a restart (recover.js) — its ⏳ / closing message already exist, so none is posted again; the embed is brought up to date, and a swap that finished while the bot was down gets its closing message now.
 * @param {import('./ticket-state.js').Ticket} t
 * @param {import('./ticket-state.js').SwapEntry} entry
 * @param {{resumed?: boolean}} [opts]
 */
export async function watchSwap (t, entry, { resumed = false } = {}) {
  const channel = entry.message.channel
  const key = `${channel.id}:${entry.swapId}`
  clearTimeout(watchers.get(key))
  watchers.delete(key)

  if (resumed) {
    if (entry.outcome) return // closed before the restart — nothing left to follow
    await entry.message.edit({ embeds: [detailsEmbed(t, entry, 'auto-detected from this ticket · auto-updated')] }).catch(() => {})
  }

  const outcome = buildOutcomeMessage(entry.latest, outcomeOpts(t, entry))
  if (outcome) {
    // Kept on the entry so a later swap can renumber it / drop its "closed soon" (syncFollowUps).
    entry.outcome = await quietReply(entry.message, { content: outcome })
    // Only a resumed swap can have a ⏳ here (it finished while the bot was down).
    await entry.processing?.delete().catch(() => {})
    entry.processing = null
    await syncFollowUps(t, entry)
    console.log(`#${channel.name}: ${entry.swapId} already ${entry.latest.status.label} — posted outcome`)
    return
  }
  // Failed / Expired / Unlocked (status.ok false) will not "complete shortly"; a resumed swap keeps the ⏳ it has (or had).
  // Kept on the entry so it can be renumbered (postSwap) and deleted once the closing message is posted — keeps the ticket clean.
  if (entry.latest.status.ok && !resumed) {
    entry.processing = await quietReply(entry.message, { content: buildProcessingMessage({ serial: serialOf(t, entry) }) })
    // A 2nd swap posted while this was sending found no ⏳ to renumber — catch up.
    await syncFollowUps(t, entry)
  }
  if (config.watchIntervalMs <= 0) return

  const startedAt = Date.now()
  let last = fingerprint(entry.latest)
  let failures = 0

  const stop = (why) => {
    watchers.delete(key)
    console.log(`#${channel.name}: stopped watching ${entry.swapId} (${why})`)
  }

  const tick = async () => {
    if (Date.now() - startedAt > config.watchMaxMs) return stop('time limit')
    try {
      const latest = await getSwap(entry.swapId)
      failures = 0
      entry.latest = latest
      rememberSwap(t, latest) // the release hash only appears later
      const next = fingerprint(latest)
      if (next !== last) {
        last = next
        // Staff may have deleted the details message — not a reason to stop.
        await entry.message.edit({ embeds: [detailsEmbed(t, entry, 'auto-detected from this ticket · auto-updated')] })
          .catch(() => {})
        console.log(`#${channel.name}: ${entry.swapId} is now ${latest.status.label} — updated details`)
      }
      const done = buildOutcomeMessage(latest, outcomeOpts(t, entry))
      if (done) {
        entry.outcome = await quietReply(entry.message, { content: done })
        // Staff may have deleted it already — not an error.
        await entry.processing?.delete().catch(() => {})
        entry.processing = null
        await syncFollowUps(t, entry)
        return stop(`${latest.status.label} — posted outcome`)
      }
    } catch (err) {
      if (CHANNEL_GONE.has(err.code)) return stop('ticket closed')
      if (++failures >= 5) return stop(`lookup failing — ${err.message}`)
    }
    watchers.set(key, setTimeout(tick, watchDelay(Date.now() - startedAt)))
  }

  watchers.set(key, setTimeout(tick, config.watchIntervalMs))
}

/** Cancel every watch in a channel — called when a ticket channel is deleted. */
export function stopWatchingChannel (channelId) {
  for (const [key, handle] of watchers) {
    if (key.startsWith(`${channelId}:`)) { clearTimeout(handle); watchers.delete(key) }
  }
}
