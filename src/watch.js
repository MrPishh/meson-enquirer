/**
 * Keeps a posted swap current until it finishes.
 *
 * Right after a swap's details embed is posted, watchSwap replies with either the closing note (already Done / Cancelled) or the ⏳ "being processed" line (still moving normally), then re-polls in the background.
 * On every status or event change it edits the details embed in place (silent — an edit notifies nobody); once the swap is Done or Cancelled it replies to that embed with the closing note, which is what the user actually gets notified about.
 *
 * Expired and Unlocked keep being watched — the cancel/refund comes later.
 * Failed stops silently (staff handle those).
 * A swap can sit in "Releasing" for many hours and Releasing never turns into Expired, so the time limit must stay generous.
 * Polling backs off with age to keep requests to Meson low.
 *
 * In-memory only: a bot restart drops every watch in flight.
 */
