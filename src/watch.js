/** The details embed for a ticket's swap entry, with its "#n" if there are several. */
export const detailsEmbed = (t, entry, sourceNote = 'auto-detected from this ticket') =>
  buildSwapEmbed(entry.latest, { serial: serialOf(t, entry), sourceNote })

/**
 * Bring a swap's ⏳, 🔎 and closing message in line with the ticket as it is now: its "Swap #n", the 🔎's reason, and whether "ticket will be closed soon" still holds.
 * Called for the earlier swaps whenever a new one is posted (postSwap), and after each send in case a swap arrived meanwhile; edits only what changed, silently.
 * @param {import('./ticket-state.js').Ticket} t
 * @param {import('./ticket-state.js').SwapEntry} entry
 */
export async function syncFollowUps (t, entry) {
  const processing = buildProcessingMessage({ serial: serialOf(t, entry) })
  if (entry.processing && entry.processing.content !== processing) {
    entry.processing = await entry.processing.edit({ content: processing }).catch(() => entry.processing)
  }
  const { supportNote } = entry.latest.status
  const support = supportNote && buildSupportMessage(supportNote, { serial: serialOf(t, entry) })
  if (entry.support && support && entry.support.content !== support) {
    entry.support = await entry.support.edit({ content: support }).catch(() => entry.support)
  }
  // "Closed soon" is only ever dropped here, never added: it belongs on the closing message of the swap that finished last.
  const opts = outcomeOpts(t, entry)
  const outcome = entry.outcome && buildOutcomeMessage(entry.latest, { ...opts, closingSoon: opts.closingSoon && entry.outcome.content.includes(CLOSING_SOON) })
  if (entry.outcome && outcome && entry.outcome.content !== outcome) {
    entry.outcome = await entry.outcome.edit({ content: outcome }).catch(() => entry.outcome)
  }
}

/**
 * Follow a just-posted swap: post its closing note if it is already finished; otherwise post its ⏳ (if it is moving normally) or 🔎 (if the support team has to step in) and start re-checking it.
 * `resumed`: the swap was rebuilt after a restart (recover.js) — its ⏳ / 🔎 / closing message already exist, so none is posted again; the embed is brought up to date, a swap that finished while the bot was down gets its closing message now, and one that became stuck meanwhile gets its 🔎.
 * A failed post never ends the follow-up: the swap is still watched, so its check rounds post the closing message, the 🔎 (the status still calls for it) or the ⏳ (via `processingOwed`) once Discord works. Only a ticket that is gone stops it.
 * With following switched off (SWAP_WATCH_INTERVAL_SECONDS=0) no ⏳ or 🔎 is posted, since nothing would ever take it down.
 * @param {import('./ticket-state.js').Ticket} t
 * @param {import('./ticket-state.js').SwapEntry} entry
 * @param {{resumed?: boolean}} [opts]
 */
export async function watchSwap (t, entry, { resumed = false } = {}) {
  const channel = entry.message.channel
  const key = `${channel.id}:${entry.swapId}`
  watchers.delete(key)

  if (resumed) {
    if (entry.outcome) {
      // Closed before the restart — nothing left to follow. A ⏳ or 🔎 still up means the bot stopped between the two steps.
      await entry.processing?.delete().catch(() => {})
      entry.processing = null
      await entry.support?.delete().catch(() => {})
      entry.support = null
      return
    }
    await entry.message.edit({ embeds: [detailsEmbed(t, entry, 'auto-detected from this ticket · auto-updated')] }).catch(() => {})
  }

  const following = config.watchIntervalMs > 0
  // Failed / Expired / Unlocked / stuck (status.ok false) will not "complete shortly": no ⏳ — and a resumed swap that became one while the bot was down has its ⏳ changed to the 🔎. A resumed swap still moving normally keeps the ⏳ it has (or had).
  const wantsProcessing = entry.latest.status.ok && !resumed && following
  let refusedUntil = 0
  try {
    const outcome = buildOutcomeMessage(entry.latest, outcomeOpts(t, entry))
    if (outcome) {
      await postClosing(t, entry, outcome)
      console.log(`#${channel.name}: ${entry.swapId} already ${entry.latest.status.label} — posted outcome`)
      return
    }
    if (wantsProcessing) await postProcessing(t, entry)
    if (following) await syncSupport(t, entry, channel)
    else if (!entry.latest.status.ok && entry.processing) await withdrawProcessing(entry, channel, entry.latest)
  } catch (err) {
    if (CHANNEL_GONE.has(err.code)) return console.log(`#${channel.name}: not following ${entry.swapId} — ticket closed`)
    if (discordRefused(err)) refusedUntil = Date.now() + REFUSED_PAUSE_MS
    entry.processingOwed = wantsProcessing && !entry.processing && !isFinished(entry.latest.status)
    console.error(`#${channel.name}: could not post the follow-up for ${entry.swapId}, will try again —`, err.message)
  }
  if (!following) return

  // Checked from the next round on, together with every other due swap.
  watchers.set(key, { key, t, entry, channel, startedAt: Date.now(), last: fingerprint(entry.latest), dueAt: Math.max(Date.now(), refusedUntil), refusedUntil })
  scheduleRound()
}

/** Cancel every watch in a channel — called when a ticket channel is deleted. */
export function stopWatchingChannel (channelId) {
  for (const key of watchers.keys()) {
    if (key.startsWith(`${channelId}:`)) watchers.delete(key)
  }
}
