/**
 * Keeps a posted swap current until it finishes.
 *
 * Right after a swap's details embed is posted, watchSwap replies with the closing note if it is already finished (Done / Released / Cancelled); otherwise a swap still moving normally gets the ⏳ "being processed" line straight away, and it re-polls in the background.
 * On every status or event change it edits the details embed in place (silent — an edit notifies nobody); once the swap is finished it replies to that embed with the closing note, which is what the user actually gets notified about, and deletes its ⏳ line.
 * syncFollowUps keeps a swap's ⏳ / closing note labelled "Swap #n" and drops "closed soon" when another swap joins the ticket.
 *
 * Expired, Unlocked, Failed and stuck Releasing swaps keep being watched — they are resolved by the team, and every swap ends finished. A swap is never dropped: it is followed until it finishes or its ticket is closed.
 * When a swap stops moving normally (status.ok turns false — stuck, Expired…), its ⏳ "completed shortly" reply is edited into a 🔎 reply saying the support team will look into it, since that promise no longer holds; it turns back into the ⏳ if the swap moves on, and is deleted once the swap finishes.
 * Polling backs off with the swap's age (since it was requested) to keep requests to Meson low — down to every SWAP_WATCH_LONG_INTERVAL_MINUTES for old swaps — and each wait is randomised (jitter) so checks never come at a fixed beat; a failed check (Meson down) never ends the watch.
 * There is one shared check round, not a timer per swap: every swap that is due is re-checked in the same request (getSwaps), across all tickets.
 *
 * In-memory only: a bot restart drops every watch in flight, and recover.js resumes them on startup (watchSwap `resumed`). Ages count from the swap's request time, so a restart does not make an old swap fast-polled again.
 */
