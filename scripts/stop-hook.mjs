/**
 * Claude Code Stop hook (.claude/settings.json): when Claude is about to finish a turn, rebuild the index and run `build-index.mjs --check`; if docs or index have drifted, tell Claude to fix them before finishing.
 *
 * Only acts when the working tree changed since its last clean check (a fingerprint of `git diff HEAD` and the untracked files, kept in .git/), so a turn that edits nothing — a question, a log check — is never held up by drift that was already there.
 * It blocks at most once in a row: if Claude still leaves drift after being told (`stop_hook_active`), the turn ends and the user sees the remaining drift instead of Claude looping.
 * Reads the hook payload (JSON) from stdin; never fails the turn on its own errors.
 */
// ----- Contents (generated by `npm run index` — do not edit) -----
// L21  Working-tree fingerprint
// L29    git()
// L34    fingerprint()
// L44  Hook
// L49    reply()
// ----- end of contents -----

import { execFileSync, spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, statSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// =============================================================================
//   Working-tree fingerprint
// =============================================================================

/** Project root (the folder above scripts/). */
const ROOT = fileURLToPath(new URL('../', import.meta.url))

/** Run git in the project and return its output, or null when git is unavailable / this is not a repository. */
const git = (...args) => {
  try { return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 }) } catch { return null }
}

/** A hash of everything that differs from the last commit — tracked changes and untracked files (by size and time) — or null outside git. */
function fingerprint () {
  const diff = git('diff', 'HEAD')
  const untracked = git('ls-files', '--others', '--exclude-standard')
  if (diff === null || untracked === null) return null
  const files = untracked.split('\n').filter(Boolean).map((f) => {
    try { const s = statSync(`${ROOT}/${f}`); return `${f}:${s.size}:${s.mtimeMs}` } catch { return f }
  })
  return createHash('sha256').update(diff).update(files.join('\n')).digest('hex')
}

// =============================================================================
//   Hook
// =============================================================================

/** Answer Claude Code (JSON on stdout) and end. */
const reply = (obj) => { if (obj) process.stdout.write(JSON.stringify(obj)); process.exit(0) }

let payload = {}
try { payload = JSON.parse(readFileSync(0, 'utf8') || '{}') } catch {}

try {
  // Bring the generated parts up to date first — edits made through the shell skip the PostToolUse hook.
  spawnSync(process.execPath, ['scripts/build-index.mjs'], { cwd: ROOT, stdio: 'ignore' })

  const gitDir = git('rev-parse', '--absolute-git-dir')?.trim()
  const stateFile = gitDir ? `${gitDir}/claude-doc-check` : null
  const now = fingerprint()
  let last = null
  try { last = stateFile && readFileSync(stateFile, 'utf8') } catch {}
  if (now && now === last) reply()

  const check = spawnSync(process.execPath, ['scripts/build-index.mjs', '--check'], { cwd: ROOT, encoding: 'utf8' })
  const report = `${check.stdout ?? ''}${check.stderr ?? ''}`.trim()
  const remember = () => { if (stateFile && now) try { writeFileSync(stateFile, now) } catch {} }

  if (check.status === 0) { remember(); reply() }
  if (payload.stop_hook_active) {
    remember()
    reply({ systemMessage: `Doc drift is still there after one fix attempt — please review:\n${report}` })
  }
  reply({ decision: 'block', reason: `The docs or index have drifted from the code. Fix every "doc drift" error below (update CLAUDE.md / README.md / .env.example as needed — warnings are optional), then finish; if one should not be fixed, say why.\n\n${report}` })
} catch (err) {
  reply({ systemMessage: `stop-hook: could not run the doc check — ${err.message}` })
}
