import { watch as fsWatch } from 'node:fs'
import { readFile, readdir, writeFile } from 'node:fs/promises'

const ROOT = new URL('../', import.meta.url)
const DIRS = ['src', 'scripts']
const CHECK = process.argv.includes('--check')
const WATCH = process.argv.includes('--watch')

const TOC_START = '// ----- Contents (generated by `npm run index` — do not edit) -----'
const TOC_END = '// ----- end of contents -----'
const SECTION_BAR = /^\/\/ ={20,}$/
const SECTION_NAME = /^\/\/ {3}(\S.*)$/
const FN = /^(export )?(async )?function\s+(\w+)|^(export )?class\s+(\w+)|^(export )?const\s+(\w+)\s*=\s*(async\s*)?(\([^)]*\)|\w+)\s*=>/
const CONST = /^(export )?const\s+(\w+)\s*=/
const EVENT = /^client\.(on|once)\(Events\.(\w+),\s*(\(?[\w, ]*\)?\s*=>|\w+)/

// =============================================================================
//   Parsing
// =============================================================================

/** The section name if a boxed section header (bar, `//   Name`, bar) starts at line `i`, else null. */
function sectionAt (lines, i) {
  if (!SECTION_BAR.test(lines[i]) || !SECTION_BAR.test(lines[i + 2] ?? '')) return null
  return lines[i + 1].match(SECTION_NAME)?.[1] ?? null
}

/** First sentence of the comment block ending right above line `i`. */
function purposeAbove (lines, i) {
  let j = i - 1
  if (j < 0) return ''
  const text = []
  if (lines[j].trim().endsWith('*/')) {
    while (j >= 0 && !lines[j].trim().startsWith('/*')) text.unshift(lines[j--])
    if (j >= 0) text.unshift(lines[j])
  } else {
    while (j >= 0 && lines[j].trim().startsWith('//') && !SECTION_BAR.test(lines[j])) text.unshift(lines[j--])
  }
  // First paragraph only, and nothing from the @tags on.
  const kept = []
  for (const raw of text) {
    const l = raw.trim().replace(/^\/\*\*?|\*\/$|^\*|^\/\//g, '').trim()
    if (l.startsWith('@')) break
    if (!l) { if (kept.length) break; continue }
    kept.push(l)
  }
  const flat = kept.join(' ')
  const sentence = flat.match(/^.*?[.!?](\s|$)/)?.[0] ?? flat
  const clean = sentence.trim().replace(/\|/g, '\\|')
  return clean.length > 160 ? clean.slice(0, 157) + '…' : clean
}

/** Remove a previously generated Contents block (and the blank line after it). */
function stripToc (lines) {
  const s = lines.indexOf(TOC_START)
  if (s === -1) return lines
  const e = lines.indexOf(TOC_END, s)
  if (e === -1) throw new Error(`unterminated Contents block (line ${s + 1})`)
  const after = lines[e + 1] === '' ? e + 2 : e + 1
  return [...lines.slice(0, s), ...lines.slice(after)]
}

/**
 * Sections and symbols of one file, by 0-based line index.
 * @returns {{sections: {name: string, i: number}[], symbols: {kind: string, name: string, i: number, exported: boolean, section: string|null, purpose: string, handler?: string}[]}}
 */
function parse (file, lines) {
  const sections = []
  const symbols = []
  let section = null
  lines.forEach((line, i) => {
    const sec = sectionAt(lines, i)
    if (sec) { section = sec; sections.push({ name: section, i }); return }
    const base = { i, section, purpose: purposeAbove(lines, i) }
    const ev = line.match(EVENT)
    if (ev) {
      const handler = ev[3].includes('=>') ? '(inline)' : ev[3]
      symbols.push({ ...base, kind: 'event', name: ev[2], once: ev[1] === 'once', handler, exported: false })
      return
    }
    const fn = line.match(FN)
    if (fn) {
      symbols.push({ ...base, kind: 'function', name: fn[3] ?? fn[5] ?? fn[7], exported: Boolean(fn[1] || fn[4] || fn[6]) })
      return
    }
    // Constants only for src/ — in the CLI scripts they are just parsed arguments.
    const c = file.startsWith('src/') && line.match(CONST)
    if (c) symbols.push({ ...base, kind: 'const', name: c[2], exported: Boolean(c[1]) })
  })
  return { sections, symbols }
}

/** Index just after the file's header comment (or 0 if it has none). */
function headerEnd (lines) {
  if (!lines[0]?.startsWith('/*')) return 0
  return lines.findIndex((l) => l.trim().endsWith('*/')) + 1
}

