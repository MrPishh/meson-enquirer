/**
 * Insert a fresh Contents block after the header comment. Its own length is known before insertion, so every listed line number is final.
 */
function withToc (file, original) {
  const at = headerEnd(original)
  // Drop blank lines right after the header: the block supplies the one blank line, so a file without imports does not end up with two.
  let skip = at
  while (skip < original.length && original[skip] === '') skip++
  const bare = [...original.slice(0, at), ...original.slice(skip)]
  const { sections, symbols } = parse(file, bare)
  if (!symbols.length) return bare

  const entries = []
  const label = (s) => s.kind === 'function' ? `${s.name}()` : s.kind === 'event' ? `on ${s.name}` : s.name
  const unsectioned = symbols.filter((s) => !s.section)
  for (const s of unsectioned) entries.push({ i: s.i, text: label(s), indent: '' })
  for (const sec of sections) {
    entries.push({ i: sec.i, text: sec.name, indent: '' })
    for (const s of symbols.filter((x) => x.section === sec.name)) entries.push({ i: s.i, text: label(s), indent: '  ' })
  }

  const size = entries.length + 3 // start + entries + end + blank line
  const width = String(bare.length + size).length
  const toc = [
    TOC_START,
    ...entries.map((e) => `// L${String(e.i + 1 + (e.i >= at ? size : 0)).padEnd(width)}  ${e.indent}${e.text}`),
    TOC_END,
    '',
  ]
  return [...bare.slice(0, at), ...toc, ...bare.slice(at)]
}

