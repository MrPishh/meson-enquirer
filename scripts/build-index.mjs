const table = (head, rows) => [
  `| ${head.join(' | ')} |`,
  `| ${head.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${r.join(' | ')} |`),
].join('\n')

async function buildCodeIndex (files) {
  const at = (file, i) => `\`${file}:${i + 1}\``
  const parsed = files.map(({ file, lines }) => ({ file, lines, ...parse(file, lines) }))
  const all = parsed.flatMap((p) => p.symbols.map((s) => ({ ...s, file: p.file })))

  // Settings: every setting('NAME') / required / number / bool read in src/config.js, with the config key it feeds.
  const cfg = parsed.find((p) => p.file === 'src/config.js').lines
  const settings = []
  cfg.forEach((line, i) => {
    const key = line.match(/^\s+(\w+):/)?.[1]
    if (!key) return
    for (const m of line.matchAll(/\b(?:setting|required|number|bool)\('([A-Z][A-Z0-9_]*)'/g)) settings.push([`\`${m[1]}\``, `\`${key}\``, at('src/config.js', i)])
  })

  // Slash commands: definitions from src/commands.js; handler by convention `handle` + PascalCase(name), e.g. meson-query -> handleMesonQuery.
  // Cache-busting query: in --watch mode the definitions may have just changed.
  const { COMMANDS } = await import(new URL(`src/commands.js?v=${Date.now()}`, ROOT))
  const cmd = parsed.find((p) => p.file === 'src/commands.js')
  const commands = COMMANDS.map((c) => {
    const handler = 'handle' + c.name.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('')
    const h = cmd.symbols.find((s) => s.name === handler)
    const def = cmd.lines.findIndex((l) => l.includes(`setName('${c.name}')`))
    const opts = (c.options ?? []).map((o) => `\`${o.name}\`${o.required ? '' : '?'}`).join(', ')
    return [`\`/${c.name}\``, opts, at('src/commands.js', def), h ? `\`${handler}\` ${at('src/commands.js', h.i)}` : '—', c.description]
  })

  const symbolTables = (kind, title) => parsed.flatMap((p) => {
    const list = p.symbols.filter((s) => s.kind === kind)
    if (!list.length) return []
    return [`### ${p.file}`, '', table([title, 'Section', 'Line', 'Purpose'], list.map((s) => [
      `\`${s.name}\`${s.exported ? ' `export`' : ''}`, s.section ?? '—', at(p.file, s.i), s.purpose,
    ])), '']
  })

  return [
    '# Code index',
    '',
    '> **Generated by `npm run index` (scripts/build-index.mjs) — do not edit by hand.**',
    '> Regenerated automatically before `npm start` and after Claude Code edits a code file.',
    '> Find a symbol here, then `Read` that file at that line with a small `limit`.',
    '> Each source file also opens with a matching "Contents" block.',
    '',
    '## Contents',
    '',
    '1. [Files and sections](#files-and-sections)',
    '2. [Discord events](#discord-events)',
    '3. [Slash commands](#slash-commands)',
    '4. [Settings (.env)](#settings-env)',
    '5. [Functions](#functions)',
    '6. [Constants](#constants)',
    '',
    '## Files and sections',
    '',
    table(['File', 'Lines', 'Sections (start line)', 'Purpose'], parsed.map((p) => [
      `\`${p.file}\``,
      String(p.lines.length),
      p.sections.map((s) => `${s.name} (${s.i + 1})`).join(' · ') || '—',
      purposeAbove(p.lines, headerEnd(p.lines)),
    ])),
    '',
    '## Discord events',
    '',
    table(['Event', 'Handler', 'Wired at', 'Note'], all.filter((s) => s.kind === 'event').map((e) => [
      `\`${e.name}\`${e.once ? ' (once)' : ''}`, e.handler === '(inline)' ? '(inline)' : `\`${e.handler}\``, at(e.file, e.i), e.purpose,
    ])),
    '',
    '## Slash commands',
    '',
    'Open to everyone in code; restrict per command in Discord (Server Settings → Integrations). Dispatch: `onInteraction`.',
    '',
    table(['Command', 'Options (? = optional)', 'Defined at', 'Handler', 'Description'], commands),
    '',
    '## Settings (.env)',
    '',
    'Parsed once in `src/config.js`; read everywhere else as `config.<key>`. Every one must be in `.env` (no defaults in code); meaning: `.env.example` and README § Settings.',
    '',
    table(['Env var', '`config` key', 'Parsed at'], settings),
    '',
    '## Functions',
    '',
    '`export` = importable from other files; otherwise private to its file.',
    '',
    ...symbolTables('function', 'Function'),
    '## Constants',
    '',
    ...symbolTables('const', 'Constant'),
  ].join('\n')
}

