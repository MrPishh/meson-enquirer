/** Remove a previously generated markdown Contents block (and the blank line after it). */
function stripMdToc (lines) {
  const s = lines.findIndex((l) => l.startsWith(MD_TOC_START))
  if (s === -1) return lines
  const e = lines.findIndex((l, i) => i > s && l.startsWith(MD_TOC_END))
  if (e === -1) throw new Error(`unterminated Contents block (line ${s + 1})`)
  const after = lines[e + 1] === '' ? e + 2 : e + 1
  return [...lines.slice(0, s), ...lines.slice(after)]
}

/**
 * Insert a heading Contents block (## and ### headings with their line numbers) after a long doc's title, as an HTML comment: invisible on GitHub, read by Claude in the doc's first lines.
 * Its own length is known before insertion, so every listed line number is final.
 */
function withMdToc (original) {
  if (original.length < MD_TOC_MIN_LINES) return original
  let at = original[0]?.startsWith('# ') ? 1 : 0
  if (original[at] === '') at++
  const headings = []
  let fence = false
  original.forEach((l, i) => {
    if (/^\s*```/.test(l)) fence = !fence
    const h = !fence && l.match(/^(#{2,3})\s+(.*)$/)
    if (h) headings.push({ i, text: h[2], indent: h[1].length === 3 ? '  ' : '' })
  })
  if (!headings.length) return original
  const size = headings.length + 3 // start + entries + end + blank line
  const width = String(original.length + size).length
  const toc = [
    MD_TOC_START,
    ...headings.map((h) => `L${String(h.i + 1 + (h.i >= at ? size : 0)).padEnd(width)}  ${h.indent}${h.text}`),
    MD_TOC_END,
    '',
  ]
  return [...original.slice(0, at), ...toc, ...original.slice(at)]
}

