/** Rewrite one file through `transform` (lines → lines), keeping its line endings; records it in `stale` if it changed (written unless --check). Returns the new lines. */
async function refresh (file, transform, stale) {
  const raw = await readFile(new URL(file, ROOT), 'utf8')
  const eol = raw.includes('\r\n') ? '\r\n' : '\n'
  const lines = transform(raw.split(/\r?\n/))
  const next = lines.join(eol)
  if (next !== raw) {
    stale.push(file)
    if (!CHECK) await writeFile(new URL(file, ROOT), next)
  }
  return lines
}

/** One full pass: rewrite stale Contents blocks and CODE_INDEX.md (or, with --check, only report), then report doc drift. */
async function build () {
  const stale = []
  const files = []

  for (const dir of DIRS) {
    for (const name of (await readdir(new URL(`${dir}/`, ROOT))).sort()) {
      if (!/\.m?js$/.test(name)) continue
      const file = `${dir}/${name}`
      files.push({ file, lines: await refresh(file, (l) => withToc(file, stripToc(l)), stale) })
    }
  }
  for (const name of (await readdir(ROOT)).sort()) {
    if (name.endsWith('.md') && !MD_SKIP.includes(name)) await refresh(name, (l) => withMdToc(stripMdToc(l)), stale)
  }

  const index = await buildCodeIndex(files)
  const current = await readFile(new URL('CODE_INDEX.md', ROOT), 'utf8').catch(() => '')
  if (index !== current) {
    stale.push('CODE_INDEX.md')
    if (!CHECK) await writeFile(new URL('CODE_INDEX.md', ROOT), index)
  }

  const { COMMANDS } = await import(new URL(`src/commands.js?v=${Date.now()}`, ROOT))
  const { errors, warnings } = checkDocs({
    root: ROOT,
    parsed: files.map(({ file, lines }) => ({ file, lines, ...parse(file, lines) })),
    commands: COMMANDS.map((c) => c.name),
  })
  if (errors.length) console.error(`doc drift (${errors.length}):\n${errors.map((e) => `  ${e}`).join('\n')}`)
  if (warnings.length) console.error(`warnings (${warnings.length}):\n${warnings.map((w) => `  ${w}`).join('\n')}`)

  if (CHECK) {
    if (stale.length) console.error(`out of date: ${stale.join(', ')} — run \`npm run index\``)
    if (stale.length || errors.length) process.exit(1)
    console.log('index up to date, no doc drift')
  } else if (stale.length || !WATCH) {
    console.log(stale.length ? `updated: ${stale.join(', ')}` : 'index already up to date')
  }
}

/**
 * --watch: rebuild whenever a code file under src/ or scripts/, or a doc in the project root, is saved — for edits made outside Claude Code (an editor), which the hooks do not see.
 * Our own rewrites trigger one more event, whose pass finds nothing to change, so it settles.
 * A half-saved file that fails to parse is logged, not fatal.
 */
async function watch () {
  let timer = null
  let running = Promise.resolve()
  const schedule = () => {
    clearTimeout(timer)
    timer = setTimeout(() => {
      running = running.then(build).catch((err) => console.error(`index: ${err.message}`))
    }, 300)
  }
  for (const dir of DIRS) {
    fsWatch(new URL(`${dir}/`, ROOT), (event, name) => {
      if (name && /\.m?js$/.test(name)) schedule()
    })
  }
  // CODE_INDEX.md is our own output — watching it would only loop.
  fsWatch(ROOT, (event, name) => {
    if (name && name.endsWith('.md') && name !== 'CODE_INDEX.md') schedule()
  })
  await build()
  console.log('watching src/, scripts/ and the docs — the index updates on every save (Ctrl+C to stop)')
}

;(WATCH ? watch() : build()).catch((err) => { console.error(err); process.exit(1) })
