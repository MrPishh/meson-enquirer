/**
 * Keeps the code's navigation aids line-accurate: the "Contents" block at the top of every source file, the heading Contents block of every long doc (README.md, CONTEXT.md), and CODE_INDEX.md (events, slash commands, .env settings, functions, constants — each with its section and file:line).
 * Then runs the doc-drift checks (scripts/doc-checks.mjs) on the hand-written docs: errors and warnings are printed every time.
 *
 *   npm run index            rewrite whatever is out of date, report doc drift
 *   npm run index -- --check change nothing; exit 1 if anything is out of date or a doc-drift error is found
 *   npm run index:watch      rebuild on every save — for editing by hand in an editor
 *
 * Runs automatically before `npm start`, after Claude Code edits a code file or a doc (scripts/index-hook.mjs), and when Claude finishes a turn (scripts/stop-hook.mjs, which also runs --check), so line numbers never drift.
 *
 * Conventions it relies on:
 *   - Sections:  a boxed header (a `// =====…` bar, `//   Name`, another bar) starts a section; everything until the next header belongs to it.
 *   - Contents:  the block between `// ----- Contents` and `// ----- end of contents -----` is generated — never edit it by hand.
 *   - Symbols:   top-level (column 0) function / class / const definitions, and `client.on|once(Events.X, …)` wiring.
 *   - Purpose:   first sentence of the JSDoc or // comment directly above a definition — keep those comments accurate.
 */
