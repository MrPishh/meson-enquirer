/**
 * CLI: list a wallet's swaps (one page, or the ticket's unfinished view). Never connects to Discord, but loads `.env` (the --unfinished view uses its ADDRESS_* limits, exactly as a ticket does).
 *
 *   npm run lookup-address -- 0x91ce0e9676397b160e88a6789253d77bbeb87460
 *   npm run lookup-address -- 0x91ce0e9676397b160e88a6789253d77bbeb87460 2
 *   npm run lookup-address -- https://explorer.meson.fi/address/0x91ce0e...
 *   npm run lookup-address -- 0x91ce0e9676397b160e88a6789253d77bbeb87460 --unfinished
 *
 * --unfinished runs the ticket auto-detect view instead: only swaps that are not Done or Cancelled, within the lookback window.
 */
// ----- Contents (generated by `npm run index` — do not edit) -----
// L28  row()
// ----- end of contents -----

import { listSwapsForAddress, listUnfinishedSwapsForAddress } from '../src/meson.js'
import { extractAddressCandidates } from '../src/extract.js'

const args = process.argv.slice(2)
const unfinishedOnly = args.includes('--unfinished')
const [rawInput, rawPage] = args.filter((a) => a !== '--unfinished')
if (!rawInput) {
  console.error('usage: npm run lookup-address -- <address | explorer link> [page, 1-based] [--unfinished]')
  process.exit(2)
}

const [address] = extractAddressCandidates(rawInput)

const row = (s) =>
  `${s.status.label.padEnd(10)} ${s.swapId.slice(0, 12)}…  ` +
  `${s.from.chain} ${s.from.amount} ${s.from.token} -> ${s.to.chain} ${s.to.amount} ${s.to.token}  ` +
  `fee ${s.fee.total} ${s.to.token}  requested ${s.requestedAt?.toISOString() ?? '—'}`

if (unfinishedOnly) {
  const { swaps, scanned, since, stoppedBy } = await listUnfinishedSwapsForAddress(address)
  console.log(`address: ${address}`)
  console.log(`checked ${scanned} swap(s) since ${since.toISOString()} (stopped by: ${stoppedBy}) — ${swaps.length} not Done/Cancelled\n`)
  for (const s of swaps) console.log(row(s))
  process.exit(0)
}
const humanPage = Math.max(Number(rawPage) || 1, 1)

const { swaps, page, size, hasMore } = await listSwapsForAddress(address, { page: humanPage - 1, size: 10 })
console.log(`address: ${address}`)
console.log(`page ${page + 1} (size ${size}) — ${swaps.length} result(s), ${hasMore ? 'more after this' : 'last page'}\n`)

for (const s of swaps) console.log(row(s))
