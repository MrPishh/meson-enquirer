/**
 * Run every doc-drift check.
 * @param {{root: URL, parsed: {file: string, lines: string[], sections: object[], symbols: object[]}[], commands: string[]}} input `parsed` = every indexed code file (build-index.mjs `parse`), `commands` = slash command names from COMMANDS
 * @returns {{errors: string[], warnings: string[]}}
 */
export function checkDocs ({ root, parsed, commands }) {
  const errors = []
  const warnings = []
  const docs = DOCS.map((d) => ({ ...d, lines: read(root, d.file)?.split(/\r?\n/) ?? null }))
  for (const d of docs) if (!d.lines) errors.push(`${d.file} is missing`)
  const doc = (file) => docs.find((d) => d.file === file)?.lines ?? []
  const claude = doc('CLAUDE.md')
  const code = parsed.map((p) => p.lines.join('\n')).join('\n')
  const corpus = [code, read(root, 'package.json'), read(root, 'ecosystem.config.cjs'), read(root, '.env.example')].join('\n')

  // Where each top-level definition lives.
  const definedIn = new Map()
  for (const p of parsed) for (const s of p.symbols) definedIn.set(s.name, [...(definedIn.get(s.name) ?? []), p.file])

  checkFileMap(root, claude, errors)
  checkTaskTable(claude, definedIn, errors)
  for (const d of docs.filter((x) => x.names && x.lines)) {
    for (const n of new Set(prose(d.lines).flatMap(ticks).map((t) => t.replace(/\(\)$/, '')).filter(looksLikeCode))) {
      if (!wordIn(n, corpus)) errors.push(`${d.file}: \`${n}\` does not exist in the code`)
    }
  }
  checkSettings(root, parsed, doc('README.md'), errors)
  checkCommands(claude, commands, errors)
  checkNpmScripts(root, docs, errors)
  for (const d of docs.filter((x) => x.lines)) {
    checkLineNumbers(d.file, d.lines, errors)
    checkLinks(root, d.file, d.lines, errors)
  }
  checkCode(parsed, errors, warnings)
  return { errors, warnings }
}

/** Every file in src/ and scripts/ has a row in the CLAUDE.md file map, and every row names a file that exists. */
function checkFileMap (root, claude, errors) {
  const rows = tableUnder(claude, 'File map')
  if (!rows) return errors.push('CLAUDE.md: no "File map" table')
  const listed = new Set(rows.map((r) => ticks(r[0])[0]).filter(Boolean))
  for (const f of listed) if (!existsSync(new URL(f, root))) errors.push(`CLAUDE.md file map: ${f} does not exist`)
  for (const dir of ['src', 'scripts']) {
    for (const name of readdirSync(new URL(`${dir}/`, root))) {
      if (!listed.has(`${dir}/${name}`)) errors.push(`CLAUDE.md file map: ${dir}/${name} has no row`)
    }
  }
}

/** In each "Where to look for…" row, every function or constant it names is defined in one of the files that row names. */
function checkTaskTable (claude, definedIn, errors) {
  const rows = tableUnder(claude, 'Where to look for')
  if (!rows) return errors.push('CLAUDE.md: no "Where to look for…" table')
  for (const [task, where = ''] of rows) {
    const spans = ticks(where)
    const files = spans.filter((s) => /^(src|scripts)\/[\w.-]+$/.test(s))
    if (!files.length) continue
    for (const n of new Set(spans.map((s) => s.replace(/\(\)$/, '')).filter((s) => definedIn.has(s)))) {
      const at = definedIn.get(n)
      if (!at.some((f) => files.includes(f))) errors.push(`CLAUDE.md "Where to look for…" row "${task}": \`${n}\` is not in ${files.join(' / ')} (it is in ${at.join(', ')})`)
    }
  }
}

/** The settings src/config.js reads = the keys in .env.example = the keys in .env (if present; values are never read out) = the settings README § Settings names. */
function checkSettings (root, parsed, readme, errors) {
  const cfg = parsed.find((p) => p.file === 'src/config.js')
  if (!cfg) return
  const reads = new Set([...cfg.lines.join('\n').matchAll(/\b(?:setting|required|number|bool)\('([A-Z][A-Z0-9_]*)'/g)].map((m) => m[1]))
  const keys = (text) => new Set([...text.matchAll(/^([A-Z][A-Z0-9_]*)=/gm)].map((m) => m[1]))
  const compare = (where, have) => {
    for (const n of reads) if (!have.has(n)) errors.push(`${where}: ${n} is missing (src/config.js reads it)`)
    for (const n of have) if (!reads.has(n)) errors.push(`${where}: ${n} is not read by src/config.js`)
  }
  const example = read(root, '.env.example')
  if (example === null) errors.push('.env.example is missing')
  else compare('.env.example', keys(example))
  const env = read(root, '.env')
  if (env !== null) compare('.env (local)', keys(env))
  const section = sectionUnder(readme, 'Settings')
  if (!section) return errors.push('README.md: no "Settings" section')
  compare('README.md § Settings', new Set(prose(section).flatMap(ticks).filter((t) => /^[A-Z][A-Z0-9_]{2,}$/.test(t))))
}

/** The slash commands defined in COMMANDS = the rows of the CLAUDE.md "Slash commands" table. */
function checkCommands (claude, commands, errors) {
  const rows = tableUnder(claude, 'Slash commands')
  if (!rows) return errors.push('CLAUDE.md: no "Slash commands" table')
  const listed = new Set(rows.map((r) => ticks(r[0])[0]?.match(/^\/([\w-]+)/)?.[1]).filter(Boolean))
  for (const c of commands) if (!listed.has(c)) errors.push(`CLAUDE.md "Slash commands" table: /${c} has no row`)
  for (const c of listed) if (!commands.includes(c)) errors.push(`CLAUDE.md "Slash commands" table: /${c} is not a defined command`)
}

/** Every `npm run x` / `npm start` in the docs exists in package.json, and every package.json script is documented somewhere (lifecycle hooks like prestart excepted). */
function checkNpmScripts (root, docs, errors) {
  const scripts = Object.keys(JSON.parse(read(root, 'package.json') ?? '{}').scripts ?? {})
  const mentioned = new Map()
  for (const d of docs.filter((x) => x.lines)) {
    for (const m of d.lines.join('\n').matchAll(/\bnpm (?:run ([\w:-]+)|(start|test)\b)/g)) mentioned.set(m[1] ?? m[2], d.file)
  }
  for (const [s, file] of mentioned) if (!scripts.includes(s)) errors.push(`${file}: \`npm run ${s}\` — package.json has no "${s}" script`)
  for (const s of scripts) {
    const lifecycle = /^(pre|post)/.test(s) && scripts.includes(s.replace(/^(pre|post)/, ''))
    if (!lifecycle && !mentioned.has(s)) errors.push(`package.json script "${s}" is not documented (no \`npm run ${s}\` in ${DOCS.map((d) => d.file).join(' / ')})`)
  }
}

/** Hand-written line numbers ("lines 1–75", `tickets.js:71`) go stale with every edit — only generated files carry them. */
function checkLineNumbers (file, lines, errors) {
  prose(lines).forEach((l, i) => {
    const hit = l.match(/\b[\w./-]+\.(?:m?js|cjs|ts|json|md):\d+/) ?? l.match(/\blines? \d+(?:\s*[-–]\s*\d+)?\b/i)
    if (hit) errors.push(`${file}:${i + 1}: hand-written line number "${hit[0]}" — point to a heading or a name instead (CODE_INDEX.md has the lines)`)
  })
}

/** Every relative link and #anchor in a doc resolves (web links are not checked). */
function checkLinks (root, file, lines, errors) {
  const own = anchors(lines)
  prose(lines).forEach((l, i) => {
    for (const [, target] of l.matchAll(/\[[^\]]*\]\(([^)\s]+)\)/g)) {
      if (/^[a-z]+:/i.test(target)) continue
      const [path, frag] = target.split('#')
      if (path && !existsSync(new URL(path, root))) { errors.push(`${file}:${i + 1}: link to ${path}, which does not exist`); continue }
      if (!frag) continue
      const there = path ? (path.endsWith('.md') ? anchors(read(root, path)?.split(/\r?\n/) ?? []) : null) : own
      if (there && !there.has(frag)) errors.push(`${file}:${i + 1}: link to #${frag}${path ? ` in ${path}` : ''}, which is not a heading there`)
    }
  })
}

/**
 * Code hygiene behind the index: unused imports and unused private definitions are errors; exports no other file uses, definitions without a purpose comment and definitions outside any section are warnings.
 * "Used" is a whole-word occurrence anywhere else (a mention in a comment counts), so an error is always real.
 */
function checkCode (parsed, errors, warnings) {
  const strip = (lines) => {
    const s = lines.indexOf(lines.find((l) => l.startsWith('// ----- Contents')))
    const e = lines.indexOf('// ----- end of contents -----')
    return s === -1 || e === -1 ? lines : [...lines.slice(0, s), ...lines.slice(e + 1)]
  }
  for (const p of parsed) {
    const body = strip(p.lines)
    const text = body.join('\n')
    // Unused imports.
    const noImports = body.filter((l) => !/^import\s/.test(l)).join('\n')
    for (const m of text.matchAll(/^import\s+(?:(\w+)\s*,?\s*)?(?:\{([^}]+)\})?\s*from/gm)) {
      const names = [m[1], ...(m[2] ?? '').split(',').map((x) => x.trim().split(/\s+as\s+/).pop())].filter(Boolean)
      for (const n of names) if (!wordIn(n, noImports)) errors.push(`${p.file}: import \`${n}\` is unused`)
    }
    for (const s of p.symbols.filter((x) => x.kind !== 'event')) {
      const where = `${p.file}:${s.i + 1} \`${s.name}\``
      const elsewhere = p.lines.filter((l, i) => i !== s.i && !l.startsWith('// L')).join('\n')
      if (!s.exported && !wordIn(s.name, elsewhere)) errors.push(`${where} is defined but never used`)
      if (s.exported && !parsed.some((o) => o.file !== p.file && wordIn(s.name, o.lines.join('\n')))) warnings.push(`${where} is exported but no other file uses it`)
      if (!s.purpose) warnings.push(`${where} has no purpose comment (CODE_INDEX.md shows "—")`)
      if (!s.section && p.sections.length) warnings.push(`${where} is outside any section`)
    }
  }
}
