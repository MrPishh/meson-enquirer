import { existsSync, readFileSync, readdirSync } from 'node:fs'

// =============================================================================
//   Reading the docs
// =============================================================================

/** Hand-written docs, by role: `names` = their backticked code names must exist in the code. */
const DOCS = [
  { file: 'CLAUDE.md', names: true },
  { file: 'README.md', names: true },
  { file: 'CONTEXT.md', names: false },
]

/** Start of a generated Contents block in a markdown doc (build-index.mjs writes it; its lines are not hand-written). */
export const MD_TOC_START = '<!-- Contents (generated by `npm run index` — do not edit)'

/** End of that block. */
export const MD_TOC_END = 'end of contents -->'

/** A file's text, or null if it does not exist. */
const read = (root, file) => {
  try { return readFileSync(new URL(file, root), 'utf8') } catch { return null }
}

/** Whether `name` occurs in `text` as a whole word. */
const wordIn = (name, text) => new RegExp(`(?<![\\w$])${name.replace(/\$/g, '\\$')}(?![\\w$])`).test(text)

/** Every `backticked` span in a piece of text. */
const ticks = (text) => [...text.matchAll(/`([^`]+)`/g)].map((m) => m[1])

/** A name that reads as code: camelCase, or CONSTANT_CASE of 4+ characters. */
const looksLikeCode = (n) => /^[A-Za-z_$][\w$]*$/.test(n) && (/[a-z][A-Z]/.test(n) || /^[A-Z][A-Z0-9_]{3,}$/.test(n))

/** A doc's lines with fenced code blocks and generated Contents blocks blanked (kept as '' so line numbers still match) — what is left is prose. */
function prose (lines) {
  let fence = false
  let toc = false
  return lines.map((line) => {
    if (line.startsWith(MD_TOC_START)) toc = true
    if (toc) { if (line.startsWith(MD_TOC_END)) toc = false; return '' }
    if (/^\s*```/.test(line)) { fence = !fence; return '' }
    return fence ? '' : line
  })
}

/** The rows (as cell arrays, header and divider left out) of the first table under the heading that starts with `title`, or null if there is no such heading. */
function tableUnder (lines, title) {
  const at = lines.findIndex((l) => /^#{1,6}\s/.test(l) && l.replace(/^#+\s*/, '').startsWith(title))
  if (at === -1) return null
  const rows = []
  for (let i = at + 1; i < lines.length && !/^#{1,6}\s/.test(lines[i]); i++) {
    const l = lines[i].trim()
    if (!l.startsWith('|')) { if (rows.length) break; continue }
    if (/^\|[\s:|-]+\|$/.test(l)) continue
    rows.push(l.slice(1, -1).split(/(?<!\\)\|/).map((c) => c.trim()))
  }
  return rows.slice(1)
}

/** The lines from the heading that starts with `title` up to the next heading of the same or a higher level. */
function sectionUnder (lines, title) {
  const at = lines.findIndex((l) => /^#{1,6}\s/.test(l) && l.replace(/^#+\s*/, '').startsWith(title))
  if (at === -1) return null
  const level = lines[at].match(/^#+/)[0].length
  const end = lines.findIndex((l, i) => i > at && /^#{1,6}\s/.test(l) && l.match(/^#+/)[0].length <= level)
  return lines.slice(at, end === -1 ? undefined : end)
}

/** GitHub's anchors for a doc's headings (`#where-to-look-for`), repeats numbered like GitHub does. */
function anchors (lines) {
  const seen = new Map()
  const out = new Set()
  for (const l of prose(lines)) {
    const h = l.match(/^#{1,6}\s+(.*)$/)?.[1]
    if (!h) continue
    const base = h.trim().toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, '').replace(/ /g, '-')
    const n = seen.get(base) ?? 0
    seen.set(base, n + 1)
    out.add(n ? `${base}-${n}` : base)
  }
  return out
}

